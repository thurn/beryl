//! The stores' shared core (plan K4; the crate's contract, "Stores"): what every store of
//! what cards create implements once, and the two moments the kernel ends what is stored:
//! as a duration ends, and as an object does.
//!
//! A store is a private field of [`State`] with its own file, which holds its entry type,
//! its mutators and queries (methods of `State`), and its `Store` implementation. The
//! per-field lists of the state name the store once: [`State::empty`],
//! [`crate::Large::clone_state`] and [`Relayout`] for `State`. Everything else reaches the
//! stores through the functions below, so a new kind of entry adds a variant to its store's
//! payload and nothing to any of them.

use std::fmt::Debug;
use std::hash::Hash;

use crate::bitboard::Bitboard;
use crate::fit::Misfit;
use crate::ids::Seat;
use crate::invariants::{Violation, check};
use crate::layout::Layout;
use crate::relayout::Relayout;
use crate::state::State;
use crate::table::GameTable;

/// How long something a card created lasts
/// ([CR 611.2a](https://yawgatog.com/resources/magic-rules/#R6112a)): "A continuous effect
/// generated by the resolution of a spell or ability lasts as long as stated by the spell or
/// ability creating it (such as 'until end of turn'). If no duration is stated, it lasts
/// until the end of the game."
///
/// This is the resolved form of `beryl_card`'s `Duration`: "your" is the player it names.
/// The rules say when one ends ([`State::expire`]). What is stored about an object ends with
/// the object too, whatever its duration: once it leaves its zone it no longer exists
/// ([CR 400.7](https://yawgatog.com/resources/magic-rules/#R4007)).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub enum Duration {
    /// "Until end of turn" and "this turn" (CR 514.2).
    #[default]
    EndOfTurn,
    /// "Until your next turn": it ends as that player's next turn begins.
    UntilYourNextTurn(Seat),
    /// No duration stated.
    Indefinite,
}

impl Duration {
    /// The duration as a save's description words it.
    pub(crate) fn words(self) -> String {
        match self {
            Duration::EndOfTurn => "until end of turn".to_owned(),
            Duration::UntilYourNextTurn(p) => format!("until player {}'s next turn", p.get()),
            Duration::Indefinite => "indefinitely".to_owned(),
        }
    }
}

/// What ending entries of a store changed.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub(crate) struct Ended {
    /// An entry ended.
    pub any: bool,
    /// One of them was an input of the layers, whose results are stale.
    pub layer_input: bool,
}

impl Ended {
    /// What two stores' endings changed together.
    #[inline]
    pub(crate) fn and(self, other: Ended) -> Ended {
        Ended {
            any: self.any | other.any,
            layer_input: self.layer_input | other.layer_input,
        }
    }
}

/// What a store implements once, whatever kinds of entry it holds (the crate's contract,
/// "Stores"). With `Clone` and equality, which it derives, a `Hash` of its entries alone
/// and [`Relayout`], this is everything the kernel asks of a store outside its own mutators
/// and queries.
pub(crate) trait Store<L: Layout>: Clone + Debug + Eq + Hash + Relayout {
    /// The store of a new game: nothing in it.
    fn empty() -> Self;

    /// The slots it has an entry about as an object, each the object's current incarnation.
    fn keys(&self) -> Bitboard<L::Slot>;

    /// Ends every entry about the object in `slot`, which has left its zone or ceased to
    /// exist ([CR 400.7](https://yawgatog.com/resources/magic-rules/#R4007)).
    fn forget(&mut self, slot: L::Slot) -> Ended;

    /// Ends every entry that lasts for `ended`.
    fn expire(&mut self, ended: Duration) -> Ended;

    /// Whether layout `M` has room for the entries.
    fn fits<M: Layout>(&self) -> Result<(), Misfit>;

    /// The store's own invariants in the state `s` it is part of.
    fn check(&self, s: &State<L>, t: &GameTable) -> Result<(), Violation>;

    /// What of the store a turn-start checkpoint of the board would lose, in words: the
    /// first such entry ([`State::off_board`]).
    fn lingering(&self, s: &State<L>, t: &GameTable) -> Option<String>;
}

impl<L: Layout> State<L> {
    /// Ends everything stored that lasts for `ended`: the one expiry, which the rules call
    /// as that moment comes, since the kernel moves the turn and holds none of its rules
    /// ([CR 514.2](https://yawgatog.com/resources/magic-rules/#R5142): "all 'until end of
    /// turn' and 'this turn' effects end"; an effect that lasts until a player's next turn
    /// ends as that turn begins). The layer results are stale if one of their inputs ended.
    #[inline]
    pub fn expire(&mut self, ended: Duration) {
        let done = self.effects.expire(ended).and(self.memos.expire(ended));
        self.settle_ended(done);
    }

    /// The object in `slot` has ended: it left its zone or ceased to exist
    /// ([CR 400.7](https://yawgatog.com/resources/magic-rules/#R4007): "An object that moves
    /// from one zone to another becomes a new object with no memory of, or relation to, its
    /// previous existence."), so everything stored about it ends. Each chokepoint that bumps
    /// an incarnation calls it; with nothing stored about the object it is one bit test.
    #[inline]
    pub(crate) fn forget_stored(&mut self, slot: L::Slot) {
        if self.keyed.contains(slot) {
            self.forget_keyed(slot);
        }
    }

    /// The rare path of [`State::forget_stored`], out of line: the zone move is the hottest
    /// mutator and almost never takes it.
    #[cold]
    #[inline(never)]
    fn forget_keyed(&mut self, slot: L::Slot) {
        let done = self.effects.forget(slot).and(self.memos.forget(slot));
        self.settle_ended(done);
    }

    /// The same for many objects at once, as a shuffle ends every card of a library.
    #[inline]
    pub(crate) fn forget_all_stored(&mut self, ended: Bitboard<L::Slot>) {
        let keyed = self.keyed & ended;
        if !keyed.is_empty() {
            // Every member is forgotten, so the order is nothing.
            for slot in keyed.iter() {
                self.forget_keyed(slot);
            }
        }
    }

    /// Keeps the state in agreement with entries that ended: the set of keyed slots, and
    /// `derived_dirty`.
    #[inline]
    fn settle_ended(&mut self, done: Ended) {
        if done.any {
            self.keyed = self.store_keys();
        }
        if done.layer_input {
            self.flags.derived_dirty = true;
        }
    }

    /// The slots a store has an entry about as an object: what `keyed` holds.
    fn store_keys(&self) -> Bitboard<L::Slot> {
        self.effects.keys() | self.memos.keys()
    }

    /// Whether layout `M` has room for what the stores hold ([`State::fits`]).
    pub(crate) fn stores_fit<M: Layout>(&self) -> Result<(), Misfit> {
        self.effects.fits::<M>()?;
        self.memos.fits::<M>()
    }

    /// The stores' invariants ([`State::check_invariants`]): each store's own, and that the
    /// keyed slots are exactly those a store has an entry about.
    pub(crate) fn check_stores(&self, t: &GameTable) -> Result<(), Violation> {
        self.effects.check(self, t)?;
        self.memos.check(self, t)?;
        check(
            self.keyed == self.store_keys(),
            "the keyed slots disagree with the stores",
            None,
        )
    }

    /// What of the stores a turn-start checkpoint would lose ([`State::off_board`]).
    pub(crate) fn stores_lingering(&self, t: &GameTable) -> Option<String> {
        self.effects
            .lingering(self, t)
            .or_else(|| self.memos.lingering(self, t))
    }
}
