//! The legacy accessor: raw writes of what milestone 4 (by-w8gv.7.1) deletes, which
//! therefore gets no typed mutator (the crate's contract, "The legacy accessor"). A search
//! for `legacy_mut` finds every caller milestone 4 has to move.

use beryl_card::CounterKind;

use crate::event::Event;
use crate::fixed::Full;
use crate::floating::{CastPermission, Continuous, Duration, FloatingEffect};
use crate::ids::{CardIx, Seat, SlotId};
use crate::layout::{Layout, Queue};
use crate::object::{Counters, ObjectFlags, ObjectRef};
use crate::state::State;

/// Lent by [`State::legacy_mut`]. Deleted by milestone 4 with the last of what it writes,
/// each of which a store replaces (by-w8gv.7.1):
///
/// | Behind the accessor | Written by | Replaced by |
/// | --- | --- | --- |
/// | the `effects` queue of floating continuous effects | [`Legacy::start_effect`], [`Legacy::end_effects`], and [`State::drop_stale_effects`] beside it | the Effects store, whose effects affect an object, a player, a locked-in set or the game |
/// | the `permissions` queue, with [`CastPermission`]'s `extra`, `exile` and `flashback` | [`Legacy::add_permission`], [`Legacy::end_permissions_of_turn`] | permission, cost-change and replacement payloads in the Effects store |
/// | `Player::sorceries_as_flash` | [`Legacy::set_sorceries_as_flash`] | a rule change in the Effects store |
/// | `entered_x` | [`Legacy::remember_x`] | a memo of the permanent in the Memos store |
/// | the [`ObjectFlags::LEGACY`] flags: `KICKED`, `OFFSPRING`, `IMPENDING`, `EVOKED`, `EXILED_UNTIL`, `EXILED_WITH`, `LOYALTY_ACTIVATED` | [`Legacy::set_object_flags`] | memos of the object in the Memos store |
/// | [`Counters`]' long-tail kind (`other_kind`, `other`) | [`Legacy::add_counters`], [`Legacy::remove_counters`], [`Legacy::set_counters`] | counter kinds generated from a list, each with its own count |
pub struct Legacy<'a, L: Layout>(&'a mut State<L>);

impl<L: Layout> State<L> {
    /// Lends the raw writes of what milestone 4 (by-w8gv.7.1) moves to memos and stores:
    /// [`Legacy`] lists them.
    #[inline]
    pub fn legacy_mut(&mut self) -> Legacy<'_, L> {
        Legacy(self)
    }
}

impl<L: Layout> Legacy<'_, L> {
    /// Sets or clears flags among [`ObjectFlags::LEGACY`] on an object. The layers read
    /// whether a permanent's impending cost was paid
    /// ([CR 702.176a](https://yawgatog.com/resources/magic-rules/#R702176a)), so their
    /// results are stale when that changes.
    #[inline]
    pub fn set_object_flags(&mut self, slot: L::Slot, flags: u32, on: bool) {
        debug_assert_eq!(flags & !ObjectFlags::LEGACY, 0, "a flag with a mutator");
        self.0.object_mut(slot).flags.set(flags, on);
        if flags & ObjectFlags::IMPENDING != 0 {
            self.0.flags.derived_dirty = true;
        }
    }

    /// Puts counters of a long-tail kind on an object: [`State::add_counters`] for them.
    #[inline]
    #[must_use]
    pub fn add_counters(
        &mut self,
        object: ObjectRef<L>,
        kind: CounterKind,
        amount: u8,
        layered: bool,
    ) -> Event<L> {
        debug_assert!(Counters::is_long_tail(kind));
        self.0.put_counters(object, kind, amount, layered)
    }

    /// Removes `amount` counters of a long-tail kind from an object that has that many:
    /// [`State::remove_counters`] for them.
    #[inline]
    #[must_use]
    pub fn remove_counters(
        &mut self,
        object: ObjectRef<L>,
        kind: CounterKind,
        amount: u8,
        layered: bool,
    ) -> Event<L> {
        debug_assert!(Counters::is_long_tail(kind));
        self.0.take_counters(object, kind, amount, layered)
    }

    /// Sets how many counters of a long-tail kind an object has, as one that enters with
    /// them does ([CR 122.6](https://yawgatog.com/resources/magic-rules/#R1226)).
    #[inline]
    pub fn set_counters(&mut self, slot: L::Slot, kind: CounterKind, n: u8) {
        debug_assert!(Counters::is_long_tail(kind));
        *self.0.object_mut(slot).counters.get_mut(kind) = n;
    }

    /// Starts a floating continuous effect of the card `source` on one object, with the
    /// next timestamp ([CR 611.2](https://yawgatog.com/resources/magic-rules/#R6112)): "A
    /// continuous effect may be generated by the resolution of a spell or ability." The
    /// layer results are stale from here.
    #[inline]
    pub fn start_effect(
        &mut self,
        source: CardIx,
        affected: ObjectRef<L>,
        effect: Continuous,
        duration: Duration,
    ) -> Result<(), Full> {
        let s = &mut *self.0;
        let timestamp = s.zones.next_timestamp;
        s.zones.next_timestamp = timestamp.wrapping_add(1);
        let pushed = s.effects.push(FloatingEffect {
            source,
            timestamp,
            duration,
            affected,
            effect,
        });
        s.flags.derived_dirty = true;
        pushed
    }

    /// Ends the floating effects that last for `duration`
    /// ([CR 611.2a](https://yawgatog.com/resources/magic-rules/#R6112a)): "A continuous
    /// effect generated by the resolution of a spell or ability lasts as long as stated by
    /// the spell or ability creating it". The layer results are stale if one ended.
    #[inline]
    pub fn end_effects(&mut self, duration: Duration) {
        let s = &mut *self.0;
        let before = s.effects.len();
        s.effects.retain(|e| e.duration != duration);
        if s.effects.len() != before {
            s.flags.derived_dirty = true;
        }
    }

    /// Whether a player may cast sorcery spells as though they had flash until their next
    /// turn.
    #[inline]
    pub fn set_sorceries_as_flash(&mut self, player: Seat, on: bool) {
        self.0.player_mut(player).sorceries_as_flash = on;
    }

    /// Lets a player cast a card from a zone it could not otherwise be cast from, or on
    /// other terms than its own.
    #[inline]
    pub fn add_permission(&mut self, permission: CastPermission<L>) -> Result<(), Full> {
        self.0.permissions.push(permission)
    }

    /// Ends the permissions that last this turn, and those whose card has left its zone
    /// ([CR 400.7](https://yawgatog.com/resources/magic-rules/#R4007)).
    #[inline]
    pub fn end_permissions_of_turn(&mut self) {
        let s = &mut *self.0;
        let objects = &s.objects;
        s.permissions.retain(|p| {
            !p.this_turn && objects[p.object.slot.index()].incarnation == p.object.incarnation
        });
    }

    /// Remembers the nonzero X the spell that became the permanent `object` was cast with
    /// ([CR 107.3m](https://yawgatog.com/resources/magic-rules/#R1073m)), forgetting those of
    /// permanents that have left.
    #[inline]
    pub fn remember_x(&mut self, object: ObjectRef<L>, x: u8) -> Result<(), Full> {
        let s = &mut *self.0;
        let objects = &s.objects;
        s.entered_x
            .retain(|&(r, _)| objects[r.slot.index()].incarnation == r.incarnation);
        s.entered_x.push((object, x))
    }
}
