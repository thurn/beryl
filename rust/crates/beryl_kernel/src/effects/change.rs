//! The change a continuous effect makes to a permanent in a layer, settled from the card's
//! words ([CR 613.1]): "The values of an object's characteristics are determined by starting
//! with the actual object. ... Then all applicable continuous effects are applied in a series
//! of layers".
//!
//! [CR 613.1]: https://yawgatog.com/resources/magic-rules/#R6131

use beryl_card::{
    AbilityIx, Amount, BasicLandTypes, Colors, FaceIx, GrantIx, Keywords, Layer, Modification,
    Protection, Subtype, Types, Words,
};

use crate::ids::Seat;

/// A change to a permanent in a layer, with every word of the card that wrote it settled:
/// the resolved form of `beryl_card`'s [`Modification`], as [`Duration`] is of its
/// `Duration`. The layer it applies in follows from the change
/// ([CR 613.1](https://yawgatog.com/resources/magic-rules/#R6131)).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum LayerChange {
    /// Layer 2: this player controls it.
    Control(Seat),
    /// Layer 4: "becomes [types] in addition to its other types".
    AddTypes(Types),
    /// Layer 4: "isn't a [type]".
    RemoveTypes(Types),
    /// Layer 4: "is a [types] and loses all other card types".
    SetTypes(Types),
    /// Layer 4: "is a [subtype] in addition to its other types".
    AddSubtype(Subtype),
    /// Layer 4: "is a [basic land types]", setting a land's land types and replacing the
    /// abilities of its rules text with their mana abilities ([CR 305.7]).
    ///
    /// [CR 305.7]: https://yawgatog.com/resources/magic-rules/#R3057
    SetLandTypes(BasicLandTypes),
    /// Layer 6: "gains [keywords]".
    AddKeywords(Keywords),
    /// Layer 6: "has [ability]", the ability at this index of the effect source's front
    /// face's grants.
    Grant(GrantIx),
    /// Layer 5: "is [colors]", replacing its colors.
    SetColors(Colors),
    /// Layer 5: "is [colors] in addition to its other colors".
    AddColors(Colors),
    /// Layer 6: "loses all abilities": its face's, and those effects applied before it
    /// granted.
    LoseAllAbilities,
    /// Layer 6: "loses [ability]", the ability at this index of the affected permanent's
    /// face.
    LoseAbility(AbilityIx),
    /// Layer 7a: "power is equal to [amount]", the number a characteristic-defining ability
    /// defines, read as the layer applies ([`LayerChange::Read`]).
    DefinedPower(i8),
    /// Layer 7b: "has base power and toughness [power]/[toughness]", the numbers settled.
    SetBasePt(i8, i8),
    /// Layer 7c: "gets +X/+Y".
    ModifyPt(i8, i8),
    /// Layer 7d: "switch its power and toughness".
    SwitchPt,
    /// A part of a static ability of the effect source whose amount the layers read as it
    /// applies, for each permanent it affects: the part at `part` of the modifications of the
    /// ability at `ability` of the face `face` of the source, which applies in `layer`
    /// ([CR 611.3a]): "A continuous effect generated by a static ability isn't 'locked in';
    /// it applies at any given moment to whatever its text indicates." "Power is equal to
    /// [amount]" (layer 7a, [CR 613.4a]) and "has base power and toughness equal to
    /// [amount]" (layer 7b) are read this way. The change names the expression and holds no
    /// number.
    ///
    /// [CR 611.3a]: https://yawgatog.com/resources/magic-rules/#R6113a
    /// [CR 613.4a]: https://yawgatog.com/resources/magic-rules/#R6134a
    Read {
        layer: Layer,
        face: FaceIx,
        ability: AbilityIx,
        part: u8,
    },
    /// Layer 4: "is a [subtype]", replacing its subtypes of the same kind. Last, so that the
    /// hashes of states saved before it was added keep their values.
    SetSubtype(Subtype),
    /// Layer 7a: "power is equal to [amount] and toughness is equal to [amount]", the numbers
    /// a characteristic-defining ability defines, read as the layer applies. Last, for the
    /// same reason as [`LayerChange::SetSubtype`].
    DefinedPt(i8, i8),
    /// Layer 6: "gains protection from [colors]", the colors settled. Last, for the same
    /// reason as [`LayerChange::SetSubtype`].
    AddProtection(Colors),
}

impl LayerChange {
    /// What `modification` is for an ability whose controller is `you`, printed on an object
    /// with the text changes `words`: "gain control" names that player, and a color word or
    /// subtype is what it reads as ([`beryl_card::words`]). None for one with an amount that is not a number, which a
    /// resolving effect settles as it begins and a static ability reads as its layer
    /// applies ([`LayerChange::Read`]).
    #[inline]
    pub fn resolve(modification: Modification, you: Seat, words: &Words) -> Option<LayerChange> {
        Some(match modification {
            Modification::Control => LayerChange::Control(you),
            Modification::AddTypes(types) => LayerChange::AddTypes(types),
            Modification::RemoveTypes(types) => LayerChange::RemoveTypes(types),
            Modification::SetTypes(types) => LayerChange::SetTypes(types),
            Modification::AddSubtypeWord(word) => LayerChange::AddSubtype(word.read(words)),
            Modification::SetSubtypeWord(word) => LayerChange::SetSubtype(word.read(words)),
            Modification::SetLandTypeWords(types) => LayerChange::SetLandTypes(types.read(words)),
            // "Other Merfolk have islandwalk" whose "Island" reads as "Swamp" grants
            // swampwalk (CR 612.1): the granting text is the source's, read through its words.
            Modification::AddKeywords(keywords) => {
                LayerChange::AddKeywords(words.landwalk(keywords))
            }
            Modification::Grant(grant) => LayerChange::Grant(grant),
            Modification::SetColorWords(colors) => LayerChange::SetColors(colors.read(words)),
            Modification::AddColorWords(colors) => LayerChange::AddColors(colors.read(words)),
            Modification::LoseAllAbilities => LayerChange::LoseAllAbilities,
            Modification::LoseAbility(ability) => LayerChange::LoseAbility(ability),
            Modification::SetBasePt(&Amount::Fixed(power), &Amount::Fixed(toughness)) => {
                LayerChange::SetBasePt(saturate(power), saturate(toughness))
            }
            // Read as the layers apply or list the ability: an amount, or a chosen color.
            Modification::SetPower(_)
            | Modification::SetPt(..)
            | Modification::SetBasePt(..)
            | Modification::AddProtection(Protection::ChosenColor)
            | Modification::AddChosenColor => return None,
            Modification::ModifyPt(power, toughness) => LayerChange::ModifyPt(power, toughness),
            Modification::SwitchPt => LayerChange::SwitchPt,
            Modification::AddProtection(Protection::ColorWords(colors)) => {
                LayerChange::AddProtection(colors.read(words))
            }
        })
    }

    /// The layer or sublayer it applies in
    /// ([CR 613.1](https://yawgatog.com/resources/magic-rules/#R6131),
    /// [CR 613.4](https://yawgatog.com/resources/magic-rules/#R6134)).
    #[inline]
    pub fn layer(self) -> Layer {
        match self {
            LayerChange::Control(_) => Layer::Control,
            LayerChange::AddTypes(_)
            | LayerChange::RemoveTypes(_)
            | LayerChange::SetTypes(_)
            | LayerChange::AddSubtype(_)
            | LayerChange::SetSubtype(_)
            | LayerChange::SetLandTypes(_) => Layer::Type,
            LayerChange::SetColors(_) | LayerChange::AddColors(_) => Layer::Color,
            LayerChange::AddKeywords(_)
            | LayerChange::AddProtection(_)
            | LayerChange::Grant(_)
            | LayerChange::LoseAllAbilities
            | LayerChange::LoseAbility(_) => Layer::Ability,
            LayerChange::DefinedPower(_) | LayerChange::DefinedPt(..) => Layer::PtDefining,
            LayerChange::SetBasePt(..) => Layer::PtSetting,
            LayerChange::ModifyPt(..) => Layer::PtModifying,
            LayerChange::SwitchPt => Layer::PtSwitching,
            LayerChange::Read { layer, .. } => layer,
        }
    }
}

impl LayerChange {
    /// Whether it removes abilities of the face ([`LayerChange::LoseAllAbilities`],
    /// [`LayerChange::LoseAbility`], and [`LayerChange::SetLandTypes`], which removes those
    /// of the rules text).
    #[inline]
    pub fn removes_abilities(self) -> bool {
        matches!(
            self,
            LayerChange::LoseAllAbilities
                | LayerChange::LoseAbility(_)
                | LayerChange::SetLandTypes(_)
        )
    }

    /// Whether it and `other`, applied in one layer, give the same results in either order:
    /// two equal changes, or two that only add to what a permanent has ("in addition to its
    /// other types", "gains", "gets +X/+Y"). Any change that sets or removes something may
    /// not, as "is blue" and "is red" do not. The rules ask it of permanents that entered
    /// the battlefield together, whose controllers choose the order of their timestamps only
    /// where it could change something ([CR 613.7m]).
    ///
    /// [CR 613.7m]: https://yawgatog.com/resources/magic-rules/#R6137m
    #[inline]
    pub fn commutes_with(self, other: LayerChange) -> bool {
        fn adds(change: LayerChange) -> bool {
            matches!(
                change,
                LayerChange::AddTypes(_)
                    | LayerChange::AddSubtype(_)
                    | LayerChange::AddKeywords(_)
                    | LayerChange::AddProtection(_)
                    | LayerChange::Grant(_)
                    | LayerChange::AddColors(_)
                    | LayerChange::ModifyPt(..)
            )
        }
        self == other || (adds(self) && adds(other))
    }

    /// The characteristics it may change ([`Characteristics`]), for the layers' search for
    /// effects that depend on others ([CR 613.8a]): "An effect is said to “depend on” another
    /// if (a) it's applied in the same layer (and, if applicable, sublayer) as the other
    /// effect; (b) applying the other would change the text or the existence of the first
    /// effect, what it applies to, or what it does to any of the things it applies to; and
    /// (c) neither effect is from a characteristic-defining ability or both are from
    /// characteristic-defining abilities."
    ///
    /// [CR 613.8a]: https://yawgatog.com/resources/magic-rules/#R6138a
    #[inline]
    pub fn writes(self) -> Characteristics {
        match self {
            LayerChange::Control(_) => Characteristics::CONTROLLER,
            // A card type removed takes the subtypes that go with it (CR 205.1a).
            LayerChange::AddTypes(_) | LayerChange::RemoveTypes(_) | LayerChange::SetTypes(_) => {
                Characteristics::TYPES.union(Characteristics::SUBTYPES)
            }
            // A land that becomes a basic land type gains its mana ability (CR 305.6).
            LayerChange::AddSubtype(_) => {
                Characteristics::SUBTYPES.union(Characteristics::ADDS_ABILITIES)
            }
            LayerChange::SetSubtype(_) => Characteristics::SUBTYPES,
            LayerChange::SetLandTypes(_) => Characteristics::SUBTYPES
                .union(Characteristics::ADDS_ABILITIES)
                .union(Characteristics::REMOVES_ABILITIES),
            LayerChange::SetColors(_) | LayerChange::AddColors(_) => Characteristics::COLORS,
            LayerChange::AddKeywords(_) | LayerChange::AddProtection(_) | LayerChange::Grant(_) => {
                Characteristics::ADDS_ABILITIES
            }
            LayerChange::LoseAllAbilities | LayerChange::LoseAbility(_) => {
                Characteristics::REMOVES_ABILITIES
            }
            LayerChange::DefinedPower(_)
            | LayerChange::DefinedPt(..)
            | LayerChange::SetBasePt(..)
            | LayerChange::ModifyPt(..)
            | LayerChange::SwitchPt
            | LayerChange::Read { .. } => Characteristics::PT,
        }
    }
}

/// A power or toughness as a permanent's characteristics hold it.
#[inline]
fn saturate(n: u8) -> i8 {
    i8::try_from(n).unwrap_or(i8::MAX)
}

/// The layer a modification applies in, for a static ability's part whose amount the
/// layers read ([`LayerChange::Read`]): 7a for a characteristic-defining power, 7b for a
/// base power and toughness, and 5 for the chosen color, which the layers read as they list
/// the ability.
#[inline]
pub fn read_layer(modification: Modification) -> Layer {
    match modification {
        Modification::SetPower(_) | Modification::SetPt(..) => Layer::PtDefining,
        Modification::AddChosenColor => Layer::Color,
        _ => Layer::PtSetting,
    }
}

/// A set of the characteristics continuous effects read and change, one bit each: what an
/// effect may change ([`LayerChange::writes`]) and what finding its set, its existence or
/// its amount reads, which the layers compare to find the effects that may depend on
/// others ([CR 613.8a]). Gaining and losing abilities are apart: what a face's static
/// ability rests on is that its permanent has not lost it, which only a removal changes,
/// and no filter reads abilities.
///
/// [CR 613.8a]: https://yawgatog.com/resources/magic-rules/#R6138a
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub struct Characteristics(u8);

impl Characteristics {
    pub const NONE: Characteristics = Characteristics(0);
    pub const TYPES: Characteristics = Characteristics(1);
    pub const SUBTYPES: Characteristics = Characteristics(1 << 1);
    pub const SUPERTYPES: Characteristics = Characteristics(1 << 2);
    pub const COLORS: Characteristics = Characteristics(1 << 3);
    pub const CONTROLLER: Characteristics = Characteristics(1 << 4);
    pub const PT: Characteristics = Characteristics(1 << 5);
    pub const ADDS_ABILITIES: Characteristics = Characteristics(1 << 6);
    pub const REMOVES_ABILITIES: Characteristics = Characteristics(1 << 7);
    /// What a filter may read of a permanent's layer results, and so what any static
    /// ability's set, "as long as" or counted amount may: never its power and toughness or
    /// the abilities it has.
    pub const FILTERED: Characteristics = Characteristics(
        Characteristics::TYPES.0
            | Characteristics::SUBTYPES.0
            | Characteristics::SUPERTYPES.0
            | Characteristics::COLORS.0
            | Characteristics::CONTROLLER.0,
    );
    /// What any effect may read: what a filter reads, and whether a static ability's
    /// permanent has lost it. An effect that writes nothing of this, as one that changes
    /// power and toughness or grants an ability, changes nothing another reads.
    pub const READABLE: Characteristics =
        Characteristics(Characteristics::FILTERED.0 | Characteristics::REMOVES_ABILITIES.0);

    #[inline]
    #[must_use]
    pub const fn union(self, other: Characteristics) -> Characteristics {
        Characteristics(self.0 | other.0)
    }

    #[inline]
    pub const fn intersects(self, other: Characteristics) -> bool {
        self.0 & other.0 != 0
    }
}
