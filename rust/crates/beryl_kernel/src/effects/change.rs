//! The change a continuous effect makes to a permanent in a layer, settled from the card's
//! words ([CR 613.1]): "The values of an object's characteristics are determined by starting
//! with the actual object. ... Then all applicable continuous effects are applied in a series
//! of layers".
//!
//! [CR 613.1]: https://yawgatog.com/resources/magic-rules/#R6131

use beryl_card::{
    AbilityIx, Amount, Colors, FaceIx, GrantIx, Keywords, Layer, Modification, Subtype, Types,
};

use crate::ids::Seat;

/// A change to a permanent in a layer, with every word of the card that wrote it settled:
/// the resolved form of `beryl_card`'s [`Modification`], as [`Duration`] is of its
/// `Duration`. The layer it applies in follows from the change
/// ([CR 613.1](https://yawgatog.com/resources/magic-rules/#R6131)).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum LayerChange {
    /// Layer 2: this player controls it.
    Control(Seat),
    /// Layer 4: "becomes [types] in addition to its other types".
    AddTypes(Types),
    /// Layer 4: "isn't a [type]".
    RemoveTypes(Types),
    /// Layer 4: "is a [types] and loses all other card types".
    SetTypes(Types),
    /// Layer 4: "is a [subtype]".
    AddSubtype(Subtype),
    /// Layer 6: "gains [keywords]".
    AddKeywords(Keywords),
    /// Layer 6: "has [ability]", the ability at this index of the effect source's front
    /// face's grants.
    Grant(GrantIx),
    /// Layer 5: "is [colors]", replacing its colors.
    SetColors(Colors),
    /// Layer 5: "is [colors] in addition to its other colors".
    AddColors(Colors),
    /// Layer 6: "loses all abilities": its face's, and those effects applied before it
    /// granted.
    LoseAllAbilities,
    /// Layer 6: "loses [ability]", the ability at this index of the affected permanent's
    /// face.
    LoseAbility(AbilityIx),
    /// Layer 7a: "power is equal to [amount]", the number a characteristic-defining ability
    /// defines, read as the layer applies ([`LayerChange::Read`]).
    DefinedPower(i8),
    /// Layer 7b: "has base power and toughness [power]/[toughness]", the numbers settled.
    SetBasePt(i8, i8),
    /// Layer 7c: "gets +X/+Y".
    ModifyPt(i8, i8),
    /// Layer 7d: "switch its power and toughness".
    SwitchPt,
    /// A part of a static ability of the effect source whose amount the layers read as it
    /// applies, for each permanent it affects: the part at `part` of the modifications of the
    /// ability at `ability` of the face `face` of the source, which applies in `layer`
    /// ([CR 611.3a]): "A continuous effect generated by a static ability isn't 'locked in';
    /// it applies at any given moment to whatever its text indicates." "Power is equal to
    /// [amount]" (layer 7a, [CR 613.4a]) and "has base power and toughness equal to
    /// [amount]" (layer 7b) are read this way. The change names the expression and holds no
    /// number.
    ///
    /// [CR 611.3a]: https://yawgatog.com/resources/magic-rules/#R6113a
    /// [CR 613.4a]: https://yawgatog.com/resources/magic-rules/#R6134a
    Read {
        layer: Layer,
        face: FaceIx,
        ability: AbilityIx,
        part: u8,
    },
}

impl LayerChange {
    /// What `modification` is for an ability whose controller is `you`: "gain control"
    /// names that player. None for one with an amount that is not a number, which a
    /// resolving effect settles as it begins and a static ability reads as its layer
    /// applies ([`LayerChange::Read`]).
    #[inline]
    pub fn resolve(modification: Modification, you: Seat) -> Option<LayerChange> {
        Some(match modification {
            Modification::Control => LayerChange::Control(you),
            Modification::AddTypes(types) => LayerChange::AddTypes(types),
            Modification::RemoveTypes(types) => LayerChange::RemoveTypes(types),
            Modification::SetTypes(types) => LayerChange::SetTypes(types),
            Modification::AddSubtype(subtype) => LayerChange::AddSubtype(subtype),
            Modification::AddKeywords(keywords) => LayerChange::AddKeywords(keywords),
            Modification::Grant(grant) => LayerChange::Grant(grant),
            Modification::SetColors(colors) => LayerChange::SetColors(colors),
            Modification::AddColors(colors) => LayerChange::AddColors(colors),
            Modification::LoseAllAbilities => LayerChange::LoseAllAbilities,
            Modification::LoseAbility(ability) => LayerChange::LoseAbility(ability),
            Modification::SetBasePt(&Amount::Fixed(power), &Amount::Fixed(toughness)) => {
                LayerChange::SetBasePt(saturate(power), saturate(toughness))
            }
            Modification::SetPower(_) | Modification::SetBasePt(..) => return None,
            Modification::ModifyPt(power, toughness) => LayerChange::ModifyPt(power, toughness),
            Modification::SwitchPt => LayerChange::SwitchPt,
        })
    }

    /// The layer or sublayer it applies in
    /// ([CR 613.1](https://yawgatog.com/resources/magic-rules/#R6131),
    /// [CR 613.4](https://yawgatog.com/resources/magic-rules/#R6134)).
    #[inline]
    pub fn layer(self) -> Layer {
        match self {
            LayerChange::Control(_) => Layer::Control,
            LayerChange::AddTypes(_)
            | LayerChange::RemoveTypes(_)
            | LayerChange::SetTypes(_)
            | LayerChange::AddSubtype(_) => Layer::Type,
            LayerChange::SetColors(_) | LayerChange::AddColors(_) => Layer::Color,
            LayerChange::AddKeywords(_)
            | LayerChange::Grant(_)
            | LayerChange::LoseAllAbilities
            | LayerChange::LoseAbility(_) => Layer::Ability,
            LayerChange::DefinedPower(_) => Layer::PtDefining,
            LayerChange::SetBasePt(..) => Layer::PtSetting,
            LayerChange::ModifyPt(..) => Layer::PtModifying,
            LayerChange::SwitchPt => Layer::PtSwitching,
            LayerChange::Read { layer, .. } => layer,
        }
    }
}

impl LayerChange {
    /// Whether it removes abilities ([`LayerChange::LoseAllAbilities`],
    /// [`LayerChange::LoseAbility`]).
    #[inline]
    pub fn removes_abilities(self) -> bool {
        matches!(
            self,
            LayerChange::LoseAllAbilities | LayerChange::LoseAbility(_)
        )
    }
}

/// A power or toughness as a permanent's characteristics hold it.
#[inline]
fn saturate(n: u8) -> i8 {
    i8::try_from(n).unwrap_or(i8::MAX)
}

/// The layer a modification applies in, for a static ability's part whose amount the
/// layers read ([`LayerChange::Read`]): 7a for a characteristic-defining power, 7b for a
/// base power and toughness.
#[inline]
pub fn read_layer(modification: Modification) -> Layer {
    match modification {
        Modification::SetPower(_) => Layer::PtDefining,
        _ => Layer::PtSetting,
    }
}
