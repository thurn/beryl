//! Static abilities' continuous effects: which of them the layers apply, and what their "as
//! long as" is read against.
//!
//! A [`LayerSpec`] names a set of objects and a condition in the vocabulary effects use, and
//! says more than the layers apply. What they apply is said here, in one place: [`applied`]
//! accepts a static ability or refuses it, and a game's card table is built only from those
//! it accepts ([`crate::table::TableError::Static`]). The layers then find what an ability
//! affects with no case for what was refused, and read its condition through [`holds`].
//!
//! A resolving ability's condition is read against its resolution: its targets, its X and
//! what its instructions have done. A static ability has none
//! ([CR 604.1](https://yawgatog.com/resources/magic-rules/#R6041): "Static abilities do
//! something all the time rather than being activated or triggered."). Its condition is read
//! against the permanent it is on, where "this" is that permanent, and against the game as
//! it is each time the layers run
//! ([CR 611.3a](https://yawgatog.com/resources/magic-rules/#R6113a)): "A continuous effect
//! generated by a static ability isn't 'locked in'; it applies at any given moment to
//! whatever its text indicates."

use beryl_card::{
    Amount, Behavior, CardDef, Condition, CounterKind, Effect, Filter, LayerSpec, Modification,
    Objects, Zone,
};

use crate::layout::Layout;
use crate::state::State;

/// Why the layers cannot apply a static ability: the part of it no code reads.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Unapplied {
    /// It says something only a resolving spell or ability has
    /// ([`LayerSpec::needs_a_resolution`]): a target, X, "that player", or what an
    /// instruction before did. No code could read it: a static ability never resolves.
    Resolving,
    /// It affects a set the layers do not find: any but the permanent it is on and the one
    /// that permanent is attached to. The permanents a filter accepts are settled by the
    /// layers themselves, layer by layer and in dependency order
    /// ([CR 613.8](https://yawgatog.com/resources/magic-rules/#R6138)), which they do not
    /// yet do.
    Affected,
    /// Its "as long as" reads more than the layers' inputs: anything but a cost paid for
    /// the permanent it is on and the counters on that permanent. What a characteristic or a
    /// count of permanents is depends on the layers' own results, so the condition would
    /// have to be read as they run.
    Condition,
    /// A power is set to an amount by anything but a characteristic-defining ability: by a
    /// static ability of another permanent or one with a condition, which apply in layer
    /// 7b, or by a resolving spell or ability, which would lock the amount in as it begins
    /// ([CR 608.2h](https://yawgatog.com/resources/magic-rules/#R6082h)).
    SetPower,
    /// A power is defined as an amount the layers do not read as they apply: anything but
    /// a number, a count of permanents by their characteristics and controllers, and a
    /// multiple of one.
    Amount,
}

/// Whether the layers apply a static ability's continuous effect, or why they cannot.
pub fn applied(spec: &LayerSpec) -> Result<(), Unapplied> {
    if spec.needs_a_resolution() {
        return Err(Unapplied::Resolving);
    }
    match spec.affected {
        Objects::This | Objects::AttachedTo => {}
        Objects::Target(_)
        | Objects::Those
        | Objects::TriggeredOn
        | Objects::ExiledWithThis
        | Objects::InZoneOf { .. }
        | Objects::CardsIn { .. }
        | Objects::All { .. }
        | Objects::Paid(_) => {
            return Err(Unapplied::Affected);
        }
    }
    match &spec.condition {
        Some(condition) if !reads(condition) => return Err(Unapplied::Condition),
        _ => {}
    }
    defined_power(spec).map(|_| ())
}

/// The amount a static ability defines its permanent's power as, if it does
/// ([`Modification::SetPower`]), or why the layers cannot read it. They have one path for
/// it, a characteristic-defining ability's
/// ([CR 604.3a](https://yawgatog.com/resources/magic-rules/#R6043a)): the ability "defines
/// an object's colors, subtypes, power, or toughness", "does not directly affect the
/// characteristics of any other objects" and "does not set the values of such
/// characteristics only if certain conditions are met". Its amount is read as layer 7a
/// applies, against what layers 2 to 6 made of every permanent.
pub fn defined_power(spec: &LayerSpec) -> Result<Option<&'static Amount>, Unapplied> {
    let Modification::SetPower(amount) = spec.modification else {
        return Ok(None);
    };
    if !matches!(spec.affected, Objects::This) || spec.condition.is_some() {
        return Err(Unapplied::SetPower);
    }
    read_as_the_layer_applies(amount)?;
    Ok(Some(amount))
}

/// Refuses an amount the layers cannot read as they apply: they have each permanent's
/// characteristics and controller as the layers before left them, and nothing else.
fn read_as_the_layer_applies(amount: &Amount) -> Result<(), Unapplied> {
    match *amount {
        Amount::Fixed(_) => Ok(()),
        Amount::Times(_, amount) => read_as_the_layer_applies(amount),
        Amount::Count(&Objects::All {
            zone: Zone::Battlefield,
            filter,
        }) if of_a_permanents_characteristics(filter) => Ok(()),
        _ => Err(Unapplied::Amount),
    }
}

/// Whether a filter asks only for a permanent's characteristics and who controls it.
fn of_a_permanents_characteristics(filter: Filter) -> bool {
    match filter {
        Filter::Any
        | Filter::Types(_)
        | Filter::Supertypes(_)
        | Filter::Subtype(_)
        | Filter::Colors(_)
        | Filter::Whose(_) => true,
        Filter::Tapped | Filter::ManaValueAtMost(_) | Filter::ManaValueAtMostX => false,
        Filter::Not(filter) => of_a_permanents_characteristics(*filter),
        Filter::All(filters) | Filter::AnyOf(filters) => filters
            .iter()
            .all(|&filter| of_a_permanents_characteristics(filter)),
    }
}

/// Whether an instruction, or one inside it, sets a power to an amount.
fn sets_power(effect: &Effect) -> bool {
    effect.any(&|effect| {
        matches!(
            effect,
            Effect::Modify {
                modification: Modification::SetPower(_),
                ..
            }
        )
    })
}

/// The first static ability of a card's faces, or of the abilities they grant, that the
/// layers cannot apply.
pub(crate) fn check(def: &CardDef) -> Result<(), Unapplied> {
    let abilities = || (def.faces.iter()).flat_map(|face| face.abilities.iter().chain(face.grants));
    // A resolving ability's effect cannot set a power to an amount either: it would lock
    // the number in as it begins, in a layer the engine does not have.
    if abilities()
        .any(|ability| matches!(ability.body(), Behavior::Data(effect) if sets_power(effect)))
    {
        return Err(Unapplied::SetPower);
    }
    abilities()
        .filter_map(beryl_card::Ability::layer)
        .try_for_each(applied)
}

/// Whether [`holds`] reads `condition`.
fn reads(condition: &Condition) -> bool {
    match condition {
        Condition::Paid(_) => true,
        Condition::Compare(left, _, right) => counted(left).is_some() && counted(right).is_some(),
        Condition::Not(condition) => reads(condition),
        Condition::All(conditions) | Condition::Any(conditions) => conditions.iter().all(reads),
        Condition::Did
        | Condition::WonFlip
        | Condition::Is(..)
        | Condition::EnteredThisTurn(_)
        | Condition::Token(_) => false,
    }
}

/// An amount a static ability's condition may compare.
enum Counted {
    /// A number printed on the card.
    Number(u8),
    /// The counters of a kind on the permanent with the ability.
    Counters(CounterKind),
}

/// `amount` as a static ability's condition may compare it, or `None` for any other amount.
fn counted(amount: &Amount) -> Option<Counted> {
    match amount {
        Amount::Fixed(n) => Some(Counted::Number(*n)),
        Amount::Counters(Objects::This, kind) => Some(Counted::Counters(*kind)),
        _ => None,
    }
}

/// Whether a static ability's "as long as" holds for the permanent in `slot`, which has the
/// ability. It reads only what the layers start from, never their results, so it is the
/// same before and after they run.
///
/// # Panics
///
/// For a condition [`applied`] refuses, which no static ability of a game's table has.
pub fn holds<L: Layout>(s: &State<L>, slot: L::Slot, condition: &Condition) -> bool {
    let amount = |amount: &Amount| match counted(amount) {
        Some(Counted::Number(n)) => n,
        Some(Counted::Counters(kind)) => s.counters_of(slot, kind),
        None => unreachable!("the card table refuses a static ability that compares this"),
    };
    match condition {
        // CR 702.33d: a permanent remembers each kind of cost its spell paid.
        Condition::Paid(kind) => s.paid(slot, *kind),
        Condition::Compare(left, comparison, right) => {
            comparison.holds(i32::from(amount(left)), i32::from(amount(right)))
        }
        Condition::Not(condition) => !holds(s, slot, condition),
        Condition::All(conditions) => conditions.iter().all(|c| holds(s, slot, c)),
        Condition::Any(conditions) => conditions.iter().any(|c| holds(s, slot, c)),
        Condition::Did
        | Condition::WonFlip
        | Condition::Is(..)
        | Condition::EnteredThisTurn(_)
        | Condition::Token(_) => {
            unreachable!("the card table refuses a static ability with this condition")
        }
    }
}

/// Whether a static ability's "as long as" reads the number of `kind` counters on the
/// permanent with the ability, so that a change in it may change whether the ability
/// applies.
pub fn reads_counters(condition: &Condition, kind: CounterKind) -> bool {
    let counts =
        |amount: &Amount| matches!(counted(amount), Some(Counted::Counters(k)) if k == kind);
    match condition {
        Condition::Compare(left, _, right) => counts(left) || counts(right),
        Condition::Not(condition) => reads_counters(condition, kind),
        Condition::All(conditions) | Condition::Any(conditions) => {
            conditions.iter().any(|c| reads_counters(c, kind))
        }
        Condition::Paid(_)
        | Condition::Did
        | Condition::WonFlip
        | Condition::Is(..)
        | Condition::EnteredThisTurn(_)
        | Condition::Token(_) => false,
    }
}

#[cfg(test)]
mod tests {
    use beryl_card::{
        CastingKind, Comparison, Filter, Keywords, Modification, Players, SpecIx, Types, Zone,
    };

    use super::*;

    const GAINS_FLYING: Modification = Modification::AddKeywords(Keywords::FLYING);

    fn spec(affected: Objects, condition: Option<Condition>) -> LayerSpec {
        LayerSpec {
            affected,
            condition,
            modification: GAINS_FLYING,
        }
    }

    const fn at_least(amount: Amount, n: u8) -> Condition {
        Condition::Compare(amount, Comparison::AtLeast, Amount::Fixed(n))
    }

    const TIME_COUNTERS: Amount = Amount::Counters(Objects::This, CounterKind::Time);
    const HAS_A_TIME_COUNTER: Condition = at_least(TIME_COUNTERS, 1);
    /// Impending's condition (CR 702.176a).
    const IMPENDING: Condition =
        Condition::All(&[Condition::Paid(CastingKind::Impending), HAS_A_TIME_COUNTER]);
    const CREATURES_YOU_CONTROL: Objects = Objects::All {
        zone: Zone::Battlefield,
        filter: Filter::All(&[Filter::Types(Types::CREATURE), Filter::Whose(&Players::You)]),
    };

    #[test]
    fn the_layers_apply_an_ability_of_this_permanent_or_the_one_it_is_attached_to() {
        for affected in [Objects::This, Objects::AttachedTo] {
            assert_eq!(applied(&spec(affected, None)), Ok(()));
        }
        for condition in [
            Condition::Paid(CastingKind::Impending),
            HAS_A_TIME_COUNTER,
            Condition::Not(&HAS_A_TIME_COUNTER),
            IMPENDING,
            Condition::Any(&[HAS_A_TIME_COUNTER, IMPENDING]),
        ] {
            assert_eq!(
                applied(&spec(Objects::This, Some(condition))),
                Ok(()),
                "{condition:?}"
            );
        }
    }

    /// "Other Squirrels you control have menace", "all creatures have double strike": the
    /// vocabulary says them and the layers do not apply them.
    #[test]
    fn a_static_ability_over_a_filtered_set_is_refused() {
        assert_eq!(
            applied(&spec(CREATURES_YOU_CONTROL, None)),
            Err(Unapplied::Affected)
        );
    }

    /// A static ability has no resolution, so nothing was done before it, nothing was
    /// targeted and no X was announced.
    #[test]
    fn a_static_ability_that_needs_a_resolution_is_refused() {
        let target = Objects::Target(SpecIx::new(0));
        for condition in [
            Condition::Did,
            at_least(Amount::ThatMany, 1),
            at_least(Amount::X, 1),
            at_least(Amount::Counters(Objects::Those, CounterKind::Time), 1),
            at_least(Amount::Power(target), 4),
            Condition::Is(target, Filter::Any),
            Condition::Is(Objects::This, Filter::ManaValueAtMostX),
            Condition::Is(Objects::This, Filter::Whose(&Players::ThatPlayer)),
            Condition::All(&[Condition::Paid(CastingKind::Evoke), Condition::Did]),
            Condition::Not(&Condition::Did),
        ] {
            assert_eq!(
                applied(&spec(Objects::This, Some(condition))),
                Err(Unapplied::Resolving),
                "{condition:?}"
            );
        }
        for affected in [target, Objects::Those] {
            assert_eq!(applied(&spec(affected, None)), Err(Unapplied::Resolving));
        }
    }

    /// "As long as you control a red creature", "as long as it's a creature": what they read
    /// is the layers' own result.
    #[test]
    fn a_condition_on_what_the_layers_decide_is_refused() {
        for condition in [
            at_least(Amount::Count(&CREATURES_YOU_CONTROL), 1),
            at_least(Amount::Power(Objects::This), 4),
            at_least(
                Amount::Counters(Objects::AttachedTo, CounterKind::PlusOne),
                1,
            ),
            at_least(Amount::Times(2, &TIME_COUNTERS), 2),
            Condition::Is(Objects::This, Filter::Types(Types::CREATURE)),
            Condition::Any(&[
                HAS_A_TIME_COUNTER,
                Condition::Is(Objects::This, Filter::Tapped),
            ]),
        ] {
            assert_eq!(
                applied(&spec(Objects::This, Some(condition))),
                Err(Unapplied::Condition),
                "{condition:?}"
            );
        }
    }

    #[test]
    fn a_condition_reads_the_counters_it_compares() {
        assert!(reads_counters(&IMPENDING, CounterKind::Time));
        assert!(!reads_counters(&IMPENDING, CounterKind::Loyalty));
        assert!(reads_counters(
            &Condition::Not(&HAS_A_TIME_COUNTER),
            CounterKind::Time
        ));
        assert!(!reads_counters(
            &Condition::Paid(CastingKind::Impending),
            CounterKind::Time
        ));
    }
}
