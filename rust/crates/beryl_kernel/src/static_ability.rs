//! Static abilities' continuous effects: which of them the layers apply, and what their "as
//! long as" is read against.
//!
//! A [`LayerSpec`] names a set of objects and a condition in the vocabulary effects use, and
//! says more than the layers apply. What they apply is said here, in one place: [`applied`]
//! accepts a static ability or refuses it, and a game's card table is built only from those
//! it accepts ([`crate::table::TableError::Static`]). The layers then find what an ability
//! affects with no case for what was refused, and read its condition through [`holds`].
//!
//! A resolving ability's condition is read against its resolution: its targets, its X and
//! what its instructions have done. A static ability has none
//! ([CR 604.1](https://yawgatog.com/resources/magic-rules/#R6041): "Static abilities do
//! something all the time rather than being activated or triggered."). Its condition is read
//! against the permanent it is on, where "this" is that permanent, and against the game as
//! it is each time the layers run
//! ([CR 611.3a](https://yawgatog.com/resources/magic-rules/#R6113a)): "A continuous effect
//! generated by a static ability isn't 'locked in'; it applies at any given moment to
//! whatever its text indicates."

use beryl_card::{
    Amount, Behavior, CardDef, Condition, CounterKind, Effect, Filter, LayerSpec, Modification,
    Objects, Zone,
};

use crate::layout::Layout;
use crate::state::State;

/// Why the layers cannot apply a static ability: the part of it no code reads.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Unapplied {
    /// It says something only a resolving spell or ability has
    /// ([`LayerSpec::needs_a_resolution`]): a target, X, "that player", or what an
    /// instruction before did. No code could read it: a static ability never resolves.
    Resolving,
    /// It affects a set the layers do not find: any but the permanent it is on, the one that
    /// permanent is attached to, and the permanents a filter of what the layers read
    /// accepts ([`read_by_the_layers`]). Objects in other zones have no layer results.
    Affected,
    /// Its "as long as" reads something the layers do not have as they apply: anything but
    /// a cost paid for the permanent it is on, the counters on that permanent, whether that
    /// permanent passes a filter, and the number of permanents that pass one, each filter
    /// one of what the layers read ([`read_by_the_layers`]).
    Condition,
    /// "Power is equal to [amount]" said by anything but a characteristic-defining ability:
    /// by a static ability of another permanent or one with a condition, or by a resolving
    /// spell or ability. Either sets a power alone in layer 7b, which the engine has only
    /// as a base power and toughness together ([`Modification::SetBasePt`]).
    SetPower,
    /// A power or base power and toughness is an amount the layers do not read as they
    /// apply: anything but a number, a count of permanents by their characteristics and
    /// controllers, and a multiple of one.
    Amount,
}

/// Whether the layers apply a static ability's continuous effect, or why they cannot.
pub fn applied(spec: &LayerSpec) -> Result<(), Unapplied> {
    if spec.needs_a_resolution() {
        return Err(Unapplied::Resolving);
    }
    match spec.affected {
        Objects::This | Objects::AttachedTo => {}
        Objects::All {
            zone: Zone::Battlefield,
            filter,
        } if read_by_the_layers(filter) => {}
        Objects::Target(_)
        | Objects::Those
        | Objects::TriggeredOn
        | Objects::TriggeredOnIn(_)
        | Objects::Carried
        | Objects::ExiledWithThis
        | Objects::InZoneOf { .. }
        | Objects::CardsIn { .. }
        | Objects::All { .. }
        | Objects::Paid(_) => {
            return Err(Unapplied::Affected);
        }
    }
    match &spec.condition {
        Some(condition) if !reads(condition) => return Err(Unapplied::Condition),
        _ => {}
    }
    read_amounts(spec)
}

/// Whether the layers can read each part of a static ability whose amount they read as it
/// applies, or why not. "Power is equal to [amount]" ([`Modification::SetPower`]) has one
/// path, a characteristic-defining ability's
/// ([CR 604.3a](https://yawgatog.com/resources/magic-rules/#R6043a)): the ability "defines
/// an object's colors, subtypes, power, or toughness", "does not directly affect the
/// characteristics of any other objects" and "does not set the values of such
/// characteristics only if certain conditions are met". Its amount is read as layer 7a
/// applies, against what layers 2 to 6 made of every permanent. "Has base power and
/// toughness [amount]" ([`Modification::SetBasePt`]) applies in layer 7b on any set, and its
/// amounts are read for each permanent as that layer applies.
pub fn read_amounts(spec: &LayerSpec) -> Result<(), Unapplied> {
    for modification in spec.modifications {
        match *modification {
            Modification::SetPower(amount) => {
                if !matches!(spec.affected, Objects::This) || spec.condition.is_some() {
                    return Err(Unapplied::SetPower);
                }
                read_as_the_layer_applies(amount)?;
            }
            Modification::SetBasePt(power, toughness) => {
                read_as_the_layer_applies(power)?;
                read_as_the_layer_applies(toughness)?;
            }
            _ => {}
        }
    }
    Ok(())
}

/// The amounts the part at `part` of a static ability's continuous effect reads as its
/// layer applies: the power of a [`Modification::SetPower`], or the power and toughness of
/// a [`Modification::SetBasePt`].
///
/// # Panics
///
/// For a part that reads no amount, which the layers list as a settled change instead.
pub fn amounts_of(spec: &LayerSpec, part: u8) -> (&'static Amount, Option<&'static Amount>) {
    match spec.modifications[usize::from(part)] {
        Modification::SetPower(amount) => (amount, None),
        Modification::SetBasePt(power, toughness) => (power, Some(toughness)),
        _ => unreachable!("the layers read the amounts of a part that has some"),
    }
}

/// Refuses an amount the layers cannot read as they apply: they have each permanent's
/// characteristics and controller as the layers before left them, and nothing else.
fn read_as_the_layer_applies(amount: &Amount) -> Result<(), Unapplied> {
    match *amount {
        Amount::Fixed(_) => Ok(()),
        Amount::Times(_, amount) => read_as_the_layer_applies(amount),
        Amount::Count(&Objects::All {
            zone: Zone::Battlefield,
            filter,
        }) if read_by_the_layers(filter) => Ok(()),
        _ => Err(Unapplied::Amount),
    }
}

/// Whether the layers can read `filter` of a permanent as they apply: it asks for the
/// permanent's characteristics and who controls it, which the layers before have settled,
/// or for whether it is tapped and its mana value, which no layer changes. "Mana value X or
/// less" names a resolution's X, which a static ability has none of.
pub fn read_by_the_layers(filter: Filter) -> bool {
    match filter {
        Filter::Any
        | Filter::Types(_)
        | Filter::Supertypes(_)
        | Filter::Subtype(_)
        | Filter::Colors(_)
        | Filter::Whose(_)
        | Filter::Tapped
        | Filter::ManaValueAtMost(_) => true,
        // A power is a result of layer 7, which no filter of an earlier layer may read until
        // the layers order effects by dependency.
        Filter::ManaValueAtMostX | Filter::PowerAtMost(_) => false,
        Filter::Not(filter) => read_by_the_layers(*filter),
        Filter::All(filters) | Filter::AnyOf(filters) => {
            filters.iter().all(|&filter| read_by_the_layers(filter))
        }
    }
}

/// Whether an instruction, or one inside it, sets a power to an amount.
fn sets_power(effect: &Effect) -> bool {
    effect.any(&|effect| match effect {
        Effect::Modify { modifications, .. } => modifications
            .iter()
            .any(|m| matches!(m, Modification::SetPower(_))),
        _ => false,
    })
}

/// The first static ability of a card's faces, or of the abilities they grant, that the
/// layers cannot apply.
pub(crate) fn check(def: &CardDef) -> Result<(), Unapplied> {
    let abilities = || (def.faces.iter()).flat_map(|face| face.abilities.iter().chain(face.grants));
    // A resolving ability's effect cannot set a power to an amount either: it would lock
    // the number in as it begins, in a layer the engine does not have.
    if abilities()
        .any(|ability| matches!(ability.body(), Behavior::Data(effect) if sets_power(effect)))
    {
        return Err(Unapplied::SetPower);
    }
    abilities()
        .filter_map(beryl_card::Ability::layer)
        .try_for_each(applied)
}

/// Whether [`holds`] reads `condition`.
fn reads(condition: &Condition) -> bool {
    match condition {
        Condition::Paid(_) => true,
        Condition::Compare(left, _, right) => counted(left).is_some() && counted(right).is_some(),
        Condition::Is(Objects::This, filter) => read_by_the_layers(*filter),
        Condition::Not(condition) => reads(condition),
        Condition::All(conditions) | Condition::Any(conditions) => conditions.iter().all(reads),
        Condition::Did
        | Condition::WonFlip
        | Condition::Is(..)
        | Condition::EnteredThisTurn(_)
        | Condition::DrewInDrawStep(_)
        | Condition::Token(_) => false,
    }
}

/// Whether `condition` reads the layers' own results: whether the permanent with the ability
/// passes a filter, or how many permanents do. Such a condition is read as its effect's
/// layer applies, against what the layers before it made of every permanent; any other is
/// the same before and after the layers run.
pub fn reads_results(condition: &Condition) -> bool {
    match condition {
        Condition::Is(..) => true,
        Condition::Compare(left, _, right) => [left, right]
            .into_iter()
            .any(|amount| matches!(counted(amount), Some(Counted::Permanents(_)))),
        Condition::Not(condition) => reads_results(condition),
        Condition::All(conditions) | Condition::Any(conditions) => {
            conditions.iter().any(reads_results)
        }
        Condition::Paid(_)
        | Condition::Did
        | Condition::WonFlip
        | Condition::EnteredThisTurn(_)
        | Condition::DrewInDrawStep(_)
        | Condition::Token(_) => false,
    }
}

/// An amount a static ability's condition may compare.
enum Counted {
    /// A number printed on the card.
    Number(u8),
    /// The counters of a kind on the permanent with the ability.
    Counters(CounterKind),
    /// The number of permanents the filter accepts, read for the controller of the
    /// permanent with the ability.
    Permanents(Filter),
}

/// `amount` as a static ability's condition may compare it, or `None` for any other amount.
fn counted(amount: &Amount) -> Option<Counted> {
    match amount {
        Amount::Fixed(n) => Some(Counted::Number(*n)),
        Amount::Counters(Objects::This, kind) => Some(Counted::Counters(*kind)),
        Amount::Count(Objects::All {
            zone: Zone::Battlefield,
            filter,
        }) if read_by_the_layers(*filter) => Some(Counted::Permanents(*filter)),
        _ => None,
    }
}

/// What the layers have made of the permanents so far, for a condition that reads it
/// ([`reads_results`]): the rules implement it over the results of the layers before the
/// one the condition's effect applies in.
pub trait LayerResults {
    /// Whether the permanent with the ability passes `filter`.
    fn is(&self, filter: Filter) -> bool;
    /// The number of permanents that pass `filter`, read for the controller of the
    /// permanent with the ability.
    fn count(&self, filter: Filter) -> usize;
}

/// No layer results, for a condition that reads none: what a caller passes [`holds`] for a
/// condition [`reads_results`] says no to.
pub struct NoResults;

impl LayerResults for NoResults {
    fn is(&self, _: Filter) -> bool {
        unreachable!("a condition that reads the layer results is read as they apply")
    }

    fn count(&self, _: Filter) -> usize {
        unreachable!("a condition that reads the layer results is read as they apply")
    }
}

/// Whether a static ability's "as long as" holds for the permanent in `slot`, which has the
/// ability. What the layers start from is read from the state; whether a permanent passes a
/// filter, and how many do, from `results`, what the layers have made of them so far.
///
/// # Panics
///
/// For a condition [`applied`] refuses, which no static ability of a game's table has.
pub fn holds<L: Layout>(
    s: &State<L>,
    slot: L::Slot,
    condition: &Condition,
    results: &impl LayerResults,
) -> bool {
    let amount = |amount: &Amount| match counted(amount) {
        Some(Counted::Number(n)) => i32::from(n),
        Some(Counted::Counters(kind)) => i32::from(s.counters_of(slot, kind)),
        Some(Counted::Permanents(filter)) => {
            i32::try_from(results.count(filter)).unwrap_or(i32::MAX)
        }
        None => unreachable!("the card table refuses a static ability that compares this"),
    };
    match condition {
        // CR 702.33d: a permanent remembers each kind of cost its spell paid.
        Condition::Paid(kind) => s.paid(slot, *kind),
        Condition::Compare(left, comparison, right) => {
            comparison.holds(amount(left), amount(right))
        }
        Condition::Is(Objects::This, filter) => results.is(*filter),
        Condition::Not(condition) => !holds(s, slot, condition, results),
        Condition::All(conditions) => conditions.iter().all(|c| holds(s, slot, c, results)),
        Condition::Any(conditions) => conditions.iter().any(|c| holds(s, slot, c, results)),
        Condition::Did
        | Condition::WonFlip
        | Condition::Is(..)
        | Condition::EnteredThisTurn(_)
        | Condition::DrewInDrawStep(_)
        | Condition::Token(_) => {
            unreachable!("the card table refuses a static ability with this condition")
        }
    }
}

/// Whether a static ability's "as long as" reads the number of `kind` counters on the
/// permanent with the ability, so that a change in it may change whether the ability
/// applies.
pub fn reads_counters(condition: &Condition, kind: CounterKind) -> bool {
    let counts =
        |amount: &Amount| matches!(counted(amount), Some(Counted::Counters(k)) if k == kind);
    match condition {
        Condition::Compare(left, _, right) => counts(left) || counts(right),
        Condition::Not(condition) => reads_counters(condition, kind),
        Condition::All(conditions) | Condition::Any(conditions) => {
            conditions.iter().any(|c| reads_counters(c, kind))
        }
        Condition::Paid(_)
        | Condition::Did
        | Condition::WonFlip
        | Condition::Is(..)
        | Condition::EnteredThisTurn(_)
        | Condition::DrewInDrawStep(_)
        | Condition::Token(_) => false,
    }
}

#[cfg(test)]
mod tests {
    use beryl_card::{
        CastingKind, Comparison, Filter, Keywords, Modification, Players, SpecIx, Types, Zone,
    };

    use super::*;

    const GAINS_FLYING: Modification = Modification::AddKeywords(Keywords::FLYING);

    fn spec(affected: Objects, condition: Option<Condition>) -> LayerSpec {
        LayerSpec {
            affected,
            condition,
            modifications: &[GAINS_FLYING],
        }
    }

    const fn at_least(amount: Amount, n: u8) -> Condition {
        Condition::Compare(amount, Comparison::AtLeast, Amount::Fixed(n))
    }

    const TIME_COUNTERS: Amount = Amount::Counters(Objects::This, CounterKind::Time);
    const HAS_A_TIME_COUNTER: Condition = at_least(TIME_COUNTERS, 1);
    /// Impending's condition (CR 702.176a).
    const IMPENDING: Condition =
        Condition::All(&[Condition::Paid(CastingKind::Impending), HAS_A_TIME_COUNTER]);
    const CREATURES_YOU_CONTROL: Objects = Objects::All {
        zone: Zone::Battlefield,
        filter: Filter::All(&[Filter::Types(Types::CREATURE), Filter::Whose(&Players::You)]),
    };

    #[test]
    fn the_layers_apply_an_ability_of_this_permanent_or_the_one_it_is_attached_to() {
        for affected in [Objects::This, Objects::AttachedTo] {
            assert_eq!(applied(&spec(affected, None)), Ok(()));
        }
        for condition in [
            Condition::Paid(CastingKind::Impending),
            HAS_A_TIME_COUNTER,
            Condition::Not(&HAS_A_TIME_COUNTER),
            IMPENDING,
            Condition::Any(&[HAS_A_TIME_COUNTER, IMPENDING]),
        ] {
            assert_eq!(
                applied(&spec(Objects::This, Some(condition))),
                Ok(()),
                "{condition:?}"
            );
        }
    }

    /// "Creatures you control get +1/+1", "all artifacts are blue": the layers find the
    /// permanents a filter accepts as they apply. Cards in a hand have no layer results, and
    /// "mana value X or less" has no X to read.
    #[test]
    fn a_static_ability_over_the_permanents_a_filter_accepts_is_applied() {
        assert_eq!(applied(&spec(CREATURES_YOU_CONTROL, None)), Ok(()));
        let untapped_cheap = Objects::All {
            zone: Zone::Battlefield,
            filter: Filter::All(&[Filter::Not(&Filter::Tapped), Filter::ManaValueAtMost(2)]),
        };
        assert_eq!(applied(&spec(untapped_cheap, None)), Ok(()));
        let in_hand = Objects::All {
            zone: Zone::Hand,
            filter: Filter::Any,
        };
        assert_eq!(applied(&spec(in_hand, None)), Err(Unapplied::Affected));
    }

    /// A static ability has no resolution, so nothing was done before it, nothing was
    /// targeted and no X was announced.
    #[test]
    fn a_static_ability_that_needs_a_resolution_is_refused() {
        let target = Objects::Target(SpecIx::new(0));
        for condition in [
            Condition::Did,
            at_least(Amount::ThatMany, 1),
            at_least(Amount::X, 1),
            at_least(Amount::Counters(Objects::Those, CounterKind::Time), 1),
            at_least(Amount::Power(target), 4),
            Condition::Is(target, Filter::Any),
            Condition::Is(Objects::This, Filter::ManaValueAtMostX),
            Condition::Is(Objects::This, Filter::Whose(&Players::ThatPlayer)),
            Condition::All(&[Condition::Paid(CastingKind::Evoke), Condition::Did]),
            Condition::Not(&Condition::Did),
        ] {
            assert_eq!(
                applied(&spec(Objects::This, Some(condition))),
                Err(Unapplied::Resolving),
                "{condition:?}"
            );
        }
        for affected in [target, Objects::Those] {
            assert_eq!(applied(&spec(affected, None)), Err(Unapplied::Resolving));
        }
    }

    /// "As long as you control a creature", "as long as it's a creature": the layers read
    /// them as the effect's layer applies.
    #[test]
    fn a_condition_on_what_the_layers_decide_is_read_as_they_apply() {
        for condition in [
            at_least(Amount::Count(&CREATURES_YOU_CONTROL), 1),
            Condition::Is(Objects::This, Filter::Types(Types::CREATURE)),
            Condition::Any(&[
                HAS_A_TIME_COUNTER,
                Condition::Is(Objects::This, Filter::Tapped),
            ]),
        ] {
            assert_eq!(
                applied(&spec(Objects::This, Some(condition))),
                Ok(()),
                "{condition:?}"
            );
            assert!(reads_results(&condition), "{condition:?}");
        }
        for condition in [HAS_A_TIME_COUNTER, IMPENDING] {
            assert!(!reads_results(&condition), "{condition:?}");
        }
    }

    /// "As long as its power is 4 or greater", "as long as enchanted creature has a +1/+1
    /// counter": nothing the layers read.
    #[test]
    fn a_condition_the_layers_cannot_read_is_refused() {
        for condition in [
            at_least(Amount::Power(Objects::This), 4),
            at_least(
                Amount::Counters(Objects::AttachedTo, CounterKind::PlusOne),
                1,
            ),
            at_least(Amount::Times(2, &TIME_COUNTERS), 2),
            Condition::Is(Objects::AttachedTo, Filter::Types(Types::CREATURE)),
        ] {
            assert_eq!(
                applied(&spec(Objects::This, Some(condition))),
                Err(Unapplied::Condition),
                "{condition:?}"
            );
        }
    }

    #[test]
    fn a_condition_reads_the_counters_it_compares() {
        assert!(reads_counters(&IMPENDING, CounterKind::Time));
        assert!(!reads_counters(&IMPENDING, CounterKind::Loyalty));
        assert!(reads_counters(
            &Condition::Not(&HAS_A_TIME_COUNTER),
            CounterKind::Time
        ));
        assert!(!reads_counters(
            &Condition::Paid(CastingKind::Impending),
            CounterKind::Time
        ));
    }
}
