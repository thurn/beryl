/// Starts a continuous effect of what is resolving, on one object or as a rule changed for a
/// player (see [CR 611.2](https://yawgatog.com/resources/magic-rules/#R6112)): "A continuous
/// effect may be generated by the resolution of a spell or ability." The layers have
/// applied it as this returns.
#[inline]
pub fn start<L: Layout>(
    game: &mut Game<'_, L>,
    resolution: &Resolution<'_, L>,
    effect: Continuous<L>,
    duration: Duration,
) -> Result<(), Full> {
    if let Subject::Object(object) = effect.subject()
        && !game.state.is_current(object)
    {
        return Ok(());
    }
    (game.state).start_effect(resolution.entry.card(), effect, duration)?;
    layers::refresh(game.state, game.table, game.sink)
}

/// Starts one continuous effect of what is resolving that changes each of `permanents` in
/// the layers of its parts `changes`
/// (see [CR 611.2c](https://yawgatog.com/resources/magic-rules/#R6112c)): "the set of objects it
/// affects is determined when that continuous effect begins. After that point, the set won't
/// change." They are the permanents as they are now; the effect has one timestamp, whichever
/// of them it changes and in whichever layer
/// (see [CR 613.7](https://yawgatog.com/resources/magic-rules/#R6137)).
#[inline]
pub fn start_on_set<L: Layout>(
    game: &mut Game<'_, L>,
    resolution: &Resolution<'_, L>,
    permanents: Bitboard<L::Slot>,
    changes: &[LayerChange],
    duration: Duration,
) -> Result<(), Full> {
    (game.state).start_effect_on_set(resolution.entry.card(), permanents, changes, duration)?;
    layers::refresh(game.state, game.table, game.sink)
}

/// What is resolving changes a rule of the game for the players `rule` names, read for its
/// controller as it resolves
/// (see [CR 613.11](https://yawgatog.com/resources/magic-rules/#R61311)): "Some continuous
/// effects affect game rules rather than objects." Each of them is affected by an effect
/// of their own, begun in turn order (see CR 101.4).
///
/// # Panics
///
/// For a rule change the ability resolving does not name ([`beryl_card::Ability::rule`]),
/// which the game has no number for.
pub fn change_rule<L: Layout>(
    game: &mut Game<'_, L>,
    resolution: &Resolution<'_, L>,
    rule: &'static RuleChange,
    duration: Duration,
) -> Result<(), Full> {
    let id = (game.table.rule_id(rule)).expect("a rule change its ability names");
    let you = resolution.entry.controller();
    let s = &*game.state;
    let named = (s.players()).filter(|player| filter::is_for(&rule.players, player, you));
    for player in s.players_in_turn_order(named) {
        let change = Continuous::Rule(Subject::Player(player), id);
        start(game, resolution, change, duration)?;
    }
    Ok(())
}

/// The controller of what is resolving gains control of a permanent
/// (see [CR 613.1b](https://yawgatog.com/resources/magic-rules/#R6131b)): a layer-2 effect.
/// It has not been under its new controller's control since their most recent turn began
/// (see [CR 302.6](https://yawgatog.com/resources/magic-rules/#R3026)).
pub fn gain_control<L: Layout>(
    game: &mut Game<'_, L>,
    resolution: &Resolution<'_, L>,
    object: ObjectRef<L>,
    duration: Duration,
) -> Result<(), Full> {
    let Some(permanent) = game.state.permanent(object) else {
        return Ok(());
    };
    let player = resolution.entry.controller();
    let control = Continuous::Layer(object, LayerChange::Control(player));
    start(game, resolution, control, duration)?;
    game.state.set_summoning_sick(permanent, true);
    game.settle(Event::GainControl { object, player })
}

/// [`Effect::Modify`](beryl_card::Effect::Modify): "[Objects] get, gain or become
/// [modifications] [duration]"
/// ([CR 611.2a](https://yawgatog.com/resources/magic-rules/#R6112a)): a continuous effect
/// from a resolving ability "lasts as long as stated by the spell or ability creating
/// it". It affects the permanents that are there as it begins (see CR 611.2c): "After that
/// point, the set won't change." The outcome is those permanents.
///
/// Its parts begin together, with one timestamp, and each applies in its own layer
/// (see [CR 613.6](https://yawgatog.com/resources/magic-rules/#R6136)): "If an effect should be
/// applied in different layers and/or sublayers, the parts of the effect each apply in their
/// appropriate ones."
pub(crate) fn instruction<L: Layout>(
    run: &mut Run<'_, '_, L>,
    objects: Objects,
    modifications: &[Modification],
    duration: beryl_card::Duration,
) -> Result<Outcome<L>, Stop> {
    // "You" in what it says is the ability's controller as it resolves.
    let you = run.resolution().entry.controller();
    let duration = lasting(duration, you);
    let permanents = run.permanents(objects);
    // "Gain control of": each permanent's own effect, which says it has a new controller
    // (see CR 302.6).
    if modifications.contains(&Modification::Control) {
        let mut left = permanents;
        while let Some(permanent) = run.next_permanent(&mut left) {
            let (game, resolution) = run.resolving();
            gain_control(game, resolution, permanent.into(), duration)?;
        }
    }
    let mut changes = [LayerChange::SwitchPt; MODIFY_PARTS];
    let mut parts = 0;
    let words = {
        let (game, resolution) = run.resolving();
        resolution.words(game)
    };
    for &modification in modifications {
        let change = match modification {
            Modification::Control => continue,
            // A base power and toughness are settled as the effect begins
            // (see [CR 608.2h](https://yawgatog.com/resources/magic-rules/#R6082h)): "If an
            // effect requires information from the game (such as the number of creatures on
            // the battlefield), the answer is determined only once, when the effect is
            // applied."
            Modification::SetBasePt(power, toughness) => {
                let scene = run.scene();
                let number =
                    |amount: &Amount| i8::try_from(scene.amount(*amount)).unwrap_or(i8::MAX);
                LayerChange::SetBasePt(number(power), number(toughness))
            }
            // "The color of your choice" is chosen as the effect begins, by the controller
            // of what is resolving (see CR 608.2d), and the effect gives protection from that
            // color for as long as it lasts.
            Modification::AddProtection(Protection::ChosenColor) => {
                let (game, resolution) = run.resolving();
                let ChosenValue::Color(color) =
                    choices::catalog(game, resolution, you, ChosenKind::Color, permanents.slots())?
                else {
                    unreachable!("a color is chosen as a color")
                };
                LayerChange::AddProtection(color)
            }
            // The card table refuses an effect that sets a power alone to an amount.
            modification @ (Modification::AddTypes(_)
            | Modification::RemoveTypes(_)
            | Modification::SetTypes(_)
            | Modification::AddSubtypeWord(_)
            | Modification::SetSubtypeWord(_)
            | Modification::SetLandTypeWords(_)
            | Modification::AddKeywords(_)
            | Modification::Grant(_)
            | Modification::SetPower(_)
            | Modification::SetPt(..)
            | Modification::ModifyPt(..)
            | Modification::LoseAllAbilities
            | Modification::LoseAbility(_)
            | Modification::SetColorWords(_)
            | Modification::AddColorWords(_)
            | Modification::AddChosenColor
            | Modification::SwitchPt
            | Modification::AddProtection(_)
            | Modification::GrantEscape) => match LayerChange::resolve(modification, you, &words) {
                Some(change) => change,
                None => no_primitive(&modification),
            },
        };
        // The definition check refuses more parts than there is room for.
        changes[parts] = change;
        parts += 1;
    }
    if parts > 0 {
        let (game, resolution) = run.resolving();
        start_on_set(
            game,
            resolution,
            permanents.slots(),
            &changes[..parts],
            duration,
        )?;
    }
    Ok(Outcome::acted_on(permanents.slots()))
}

/// [`Effect::ExchangeControl`](beryl_card::Effect::ExchangeControl): "exchange control of
/// [first] and [second]". The outcome is the two permanents, if they were exchanged.
///
/// see [CR 701.12a](https://yawgatog.com/resources/magic-rules/#R70112a): "When such a spell or
/// ability resolves, if the entire exchange can't be completed, no part of the exchange
/// occurs." A side that names no permanent, as a target that has become illegal or has left
/// the battlefield names none, exchanges nothing.
///
/// see [CR 701.12b](https://yawgatog.com/resources/magic-rules/#R70112b): "When control of two
/// permanents is exchanged, if those permanents are controlled by different players, each of
/// those players simultaneously gains control of the permanent that was controlled by the
/// other player. If, on the other hand, those permanents are controlled by the same player,
/// the exchange effect does nothing." The two changes of control are layer-2 effects that
/// begin together, with one timestamp, and last for the rest of the game
/// ([CR 611.2a](https://yawgatog.com/resources/magic-rules/#R6112a): "If no duration is
/// stated, it lasts until the end of the game."). Neither permanent has been under its new
/// controller's control since their most recent turn began
/// (see [CR 302.6](https://yawgatog.com/resources/magic-rules/#R3026)).
pub(crate) fn exchange_instruction<L: Layout>(
    run: &mut Run<'_, '_, L>,
    first: Objects,
    second: Objects,
) -> Result<Outcome<L>, Full> {
    let (Some(a), Some(b)) = (
        run.permanents(first).slots().sole(),
        run.permanents(second).slots().sole(),
    ) else {
        return Ok(Outcome::NOTHING);
    };
    let (game, resolution) = run.resolving();
    let (a_controller, b_controller) = (game.state.controller(a), game.state.controller(b));
    if a == b || a_controller == b_controller {
        return Ok(Outcome::NOTHING);
    }
    let (a, b) = (game.state.object_ref(a), game.state.object_ref(b));
    let exchange = [
        Continuous::Layer(a, LayerChange::Control(b_controller)),
        Continuous::Layer(b, LayerChange::Control(a_controller)),
    ];
    (game.state).start_effects(resolution.entry.card(), &exchange, Duration::Indefinite)?;
    layers::refresh(game.state, game.table, game.sink)?;
    for (object, player) in [(a, b_controller), (b, a_controller)] {
        let permanent = game
            .state
            .permanent(object)
            .expect("a permanent changing control");
        game.state.set_summoning_sick(permanent, true);
        game.settle(Event::GainControl { object, player })?;
    }
    let mut exchanged = Bitboard::single(a.slot);
    exchanged.insert(b.slot);
    Ok(Outcome::acted_on(exchanged))
}

/// A duration as a card says it, for an effect `you` control
/// ([CR 611.2a](https://yawgatog.com/resources/magic-rules/#R6112a)).
pub(crate) fn lasting(duration: beryl_card::Duration, you: Seat) -> Duration {
    match duration {
        beryl_card::Duration::EndOfTurn => Duration::EndOfTurn,
        beryl_card::Duration::UntilYourNextTurn => Duration::UntilYourNextTurn(you),
        beryl_card::Duration::Indefinite => Duration::Indefinite,
    }
}

/// [`Effect::ControlPlayer`](beryl_card::Effect::ControlPlayer): "You control [player]
/// during that player's next turn" (see [CR 724.1]): an effect on each player named, which waits
/// for that player's next turn ([`State::begin_turn`](crate::state::State::begin_turn)). The
/// outcome is how many players it is on.
///
/// [CR 724.1]: https://yawgatog.com/resources/magic-rules/#R7241
pub(crate) fn control_player_instruction<L: Layout>(
    run: &mut Run<'_, '_, L>,
    players: Players,
) -> Result<Outcome<L>, Full> {
    let controller = run.resolution().entry.controller();
    let named = run.scene().players(players);
    let (game, resolution) = run.resolving();
    let mut count = 0;
    for controlled in game.state.players_in_turn_order(named) {
        let control = Continuous::Control {
            controlled,
            controller,
        };
        // It lasts until the turn it waits for begins, which ends it (see CR 724.1b: "If a turn
        // is skipped, any pending player-controlling effects wait until the player who would
        // be affected actually takes a turn.").
        start(game, resolution, control, Duration::Indefinite)?;
        count += 1;
    }
    Ok(Outcome::of(Bitboard::EMPTY, count))
}

/// [`Effect::ExtraTurn`](beryl_card::Effect::ExtraTurn): "[Player] takes an extra turn after
/// this one" (see [CR 500.7]): an effect on each player named, which the next turn's beginning
/// takes ([`State::begin_turn`](crate::state::State::begin_turn)). They are added "one at a
/// time, in APNAP order", and "The most recently created turn will be taken first", so the
/// player last in turn order takes theirs first. The outcome is how many players it is on.
///
/// [CR 500.7]: https://yawgatog.com/resources/magic-rules/#R5007
pub(crate) fn extra_turn_instruction<L: Layout>(
    run: &mut Run<'_, '_, L>,
    players: Players,
) -> Result<Outcome<L>, Full> {
    let named = run.scene().players(players);
    let (game, resolution) = run.resolving();
    let mut count = 0;
    for player in game.state.players_in_turn_order(named) {
        // It lasts until its turn begins, which ends it.
        start(
            game,
            resolution,
            Continuous::ExtraTurn(player),
            Duration::Indefinite,
        )?;
        count += 1;
    }
    Ok(Outcome::of(Bitboard::EMPTY, count))
}

/// [`Effect::ChangeRule`](beryl_card::Effect::ChangeRule): "[Rule change] [duration]"
/// (see CR 613.11): [`change_rule`], for as long as the card says. The outcome is that it did.
pub(crate) fn change_rule_instruction<L: Layout>(
    run: &mut Run<'_, '_, L>,
    rule: &'static RuleChange,
    duration: beryl_card::Duration,
) -> Result<Outcome<L>, Full> {
    let duration = lasting(duration, run.resolution().entry.controller());
    let (game, resolution) = run.resolving();
    change_rule(game, resolution, rule, duration)?;
    Ok(Outcome::of(Bitboard::EMPTY, 1))
}

/// [`Effect::BecomeCopy`](beryl_card::Effect::BecomeCopy): "[objects] become a copy of [of],
/// except ..." (see [CR 707.2]): "When copying an object, the copy acquires the copiable values of
/// the original object’s characteristics ... Other effects (including type-changing and
/// text-changing effects), status, counters, and stickers are not copied." What it copies is the first permanent `of` names; with none left, nothing happens. The
/// exception at `except` of the resolving ability's face goes after the values it copies
/// (see [CR 707.9b]), so a copy of the copy has it too. The outcome is the permanents that became
/// copies.
///
/// [CR 707.2]: https://yawgatog.com/resources/magic-rules/#R7072
/// [CR 707.9b]: https://yawgatog.com/resources/magic-rules/#R7079b
pub(crate) fn become_copy_instruction<L: Layout>(
    run: &mut Run<'_, '_, L>,
    objects: Objects,
    of: Objects,
    except: Option<ExceptIx>,
) -> Result<Outcome<L>, Full> {
    let mut originals = run.permanents(of);
    let Some(original) = run.next_permanent(&mut originals) else {
        return Ok(Outcome::NOTHING);
    };
    let entry = &run.resolution().entry;
    let source = entry.card();
    let mut values = run.state().copiable(original.slot());
    if let Some(ix) = except {
        // Its color words read through the text changes of the spell or ability (see CR 612.1).
        let words = run.state().entry_words(entry);
        let addition = Addition::new(source, entry.face(), ix);
        values = values.with_addition_read(addition, run.game().table, &words)?;
    }
    let mut copies = run.permanents(objects);
    let mut became = Bitboard::EMPTY;
    while let Some(copy) = run.next_permanent(&mut copies) {
        run.game().state.become_copy(source, copy.into(), values)?;
        became.insert(copy.slot());
    }
    let game = run.game();
    layers::refresh(game.state, game.table, game.sink)?;
    Ok(Outcome::acted_on(became))
}
