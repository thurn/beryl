//! Continuous effects ([CR 611](https://yawgatog.com/resources/magic-rules/#R611)) that a
//! resolving spell or ability creates: each is an entry of the Effects store
//! (`beryl_kernel`'s contract, "Stores"), which the layers and the rules read by kind.

use beryl_card::{Modification, Objects, RuleChange};

use crate::bitboard::Bitboard;
use crate::event::Event;
use crate::filter;
use crate::fixed::Full;
use crate::game::Game;
use crate::ids::Seat;
use crate::interpret::{Outcome, Run, no_primitive};
use crate::layers;
use crate::layout::Layout;
use crate::resolution::Resolution;
use crate::state::{Continuous, Duration, LayerChange, ObjectRef, Subject};

/// Starts a continuous effect of what is resolving, on one object or as a rule changed for a
/// player ([CR 611.2](https://yawgatog.com/resources/magic-rules/#R6112)): "A continuous
/// effect may be generated by the resolution of a spell or ability." The layers have
/// applied it as this returns.
#[inline]
pub fn start<L: Layout>(
    game: &mut Game<'_, L>,
    resolution: &Resolution<'_, L>,
    effect: Continuous<L>,
    duration: Duration,
) -> Result<(), Full> {
    if let Subject::Object(object) = effect.subject()
        && !game.state.is_current(object)
    {
        return Ok(());
    }
    (game.state).start_effect(resolution.entry.card, effect, duration)?;
    layers::refresh(game.state, game.table, game.sink)
}

/// Starts one continuous effect of what is resolving that changes each of `permanents` in a
/// layer ([CR 611.2c](https://yawgatog.com/resources/magic-rules/#R6112c)): "the set of
/// objects it affects is determined when that continuous effect begins. After that point,
/// the set won't change." They are the permanents as they are now; the effect has one
/// timestamp, whichever of them it changes
/// ([CR 613.7](https://yawgatog.com/resources/magic-rules/#R6137)).
#[inline]
pub fn start_on_set<L: Layout>(
    game: &mut Game<'_, L>,
    resolution: &Resolution<'_, L>,
    permanents: Bitboard<L::Slot>,
    change: LayerChange,
    duration: Duration,
) -> Result<(), Full> {
    (game.state).start_effect_on_set(resolution.entry.card, permanents, change, duration)?;
    layers::refresh(game.state, game.table, game.sink)
}

/// What is resolving changes a rule of the game for the players `rule` names, read for its
/// controller as it resolves
/// ([CR 613.11](https://yawgatog.com/resources/magic-rules/#R61311)): "Some continuous
/// effects affect game rules rather than objects." Each of them is affected by an effect
/// of their own, begun in turn order (CR 101.4).
///
/// # Panics
///
/// For a rule change the ability resolving does not name ([`beryl_card::Ability::rule`]),
/// which the game has no number for.
pub fn change_rule<L: Layout>(
    game: &mut Game<'_, L>,
    resolution: &Resolution<'_, L>,
    rule: &'static RuleChange,
    duration: Duration,
) -> Result<(), Full> {
    let id = (game.table.rule_id(rule)).expect("a rule change its ability names");
    let you = resolution.entry.controller;
    let s = &*game.state;
    let named = (s.players()).filter(|player| filter::is_for(&rule.players, player, you));
    for player in s.players_in_turn_order(named) {
        let change = Continuous::Rule(Subject::Player(player), id);
        start(game, resolution, change, duration)?;
    }
    Ok(())
}

/// The controller of what is resolving gains control of a permanent
/// ([CR 613.1b](https://yawgatog.com/resources/magic-rules/#R6131b)): a layer-2 effect.
/// It has not been under its new controller's control since their most recent turn began
/// ([CR 302.6](https://yawgatog.com/resources/magic-rules/#R3026)).
pub fn gain_control<L: Layout>(
    game: &mut Game<'_, L>,
    resolution: &Resolution<'_, L>,
    object: ObjectRef<L>,
    duration: Duration,
) -> Result<(), Full> {
    if !game.on_battlefield(object) {
        return Ok(());
    }
    let player = resolution.entry.controller;
    let control = Continuous::Layer(object, LayerChange::Control(player));
    start(game, resolution, control, duration)?;
    game.state.set_summoning_sick(object.slot, true);
    game.settle(Event::GainControl { object, player })
}

/// [`Effect::Modify`](beryl_card::Effect::Modify): "[Objects] get, gain or become
/// [modification] [duration]"
/// ([CR 611.2a](https://yawgatog.com/resources/magic-rules/#R6112a)): a continuous effect
/// from a resolving ability "lasts as long as stated by the spell or ability creating
/// it". It affects the permanents that are there as it begins (CR 611.2c): "After that
/// point, the set won't change." The outcome is those permanents.
pub(crate) fn instruction<L: Layout>(
    run: &mut Run<'_, '_, L>,
    objects: Objects,
    modification: Modification,
    duration: beryl_card::Duration,
) -> Result<Outcome<L>, Full> {
    // "You" in what it says is the ability's controller as it resolves.
    let you = run.resolution().entry.controller;
    let duration = lasting(duration, you);
    let permanents = run.permanents(objects);
    // "Gain control of": each permanent's own effect, which says it has a new controller
    // (CR 302.6).
    if modification == Modification::Control {
        let mut left = permanents;
        while let Some(permanent) = run.next_permanent(&mut left) {
            let (game, resolution) = run.resolving();
            gain_control(game, resolution, permanent, duration)?;
        }
        return Ok(Outcome::acted_on(permanents));
    }
    // The card table refuses an effect that sets a power to an amount.
    let Some(change) = LayerChange::resolve(modification, you) else {
        no_primitive(&modification)
    };
    // One effect, with one timestamp, on the set as it is now
    // ([CR 613.7](https://yawgatog.com/resources/magic-rules/#R6137): "An effect with an
    // earlier timestamp is applied before an effect with a later timestamp.").
    let (game, resolution) = run.resolving();
    start_on_set(game, resolution, permanents, change, duration)?;
    Ok(Outcome::acted_on(permanents))
}

/// A duration as a card says it, for an effect `you` control
/// ([CR 611.2a](https://yawgatog.com/resources/magic-rules/#R6112a)).
fn lasting(duration: beryl_card::Duration, you: Seat) -> Duration {
    match duration {
        beryl_card::Duration::EndOfTurn => Duration::EndOfTurn,
        beryl_card::Duration::UntilYourNextTurn => Duration::UntilYourNextTurn(you),
        beryl_card::Duration::Indefinite => Duration::Indefinite,
    }
}

/// [`Effect::ChangeRule`](beryl_card::Effect::ChangeRule): "[Rule change] [duration]"
/// (CR 613.11): [`change_rule`], for as long as the card says. The outcome is that it did.
pub(crate) fn change_rule_instruction<L: Layout>(
    run: &mut Run<'_, '_, L>,
    rule: &'static RuleChange,
    duration: beryl_card::Duration,
) -> Result<Outcome<L>, Full> {
    let duration = lasting(duration, run.resolution().entry.controller);
    let (game, resolution) = run.resolving();
    change_rule(game, resolution, rule, duration)?;
    Ok(Outcome::of(Bitboard::EMPTY, 1))
}
