//! How a card body or an instruction starts a continuous effect: an entry of the Effects
//! store (`beryl_kernel`'s contract, "Stores"), which the layers and the rules read by kind.

use super::EffectCtx;
use crate::bitboard::Bitboard;
use crate::event;
use crate::layers;
use crate::layout::Layout;
use crate::state::{Affects, Duration, LayerChange, ObjectRef, Payload};

impl<L: Layout> EffectCtx<'_, L> {
    /// Starts a continuous effect from this ability on one object, or a rule change on a player
    /// ([CR 611.2](https://yawgatog.com/resources/magic-rules/#R6112)): "A continuous effect may
    /// be generated by the resolution of a spell or ability."
    pub fn add_effect(&mut self, on: impl Into<Affects<L>>, payload: Payload, duration: Duration) {
        let affected = on.into();
        if affected
            .as_object()
            .is_some_and(|r| !self.game.state.is_current(r))
        {
            return;
        }
        let source = self.resolution.entry.card;
        let pushed = self
            .game
            .state
            .start_effect(source, affected, payload, duration);
        self.check(pushed);
        let refreshed = layers::refresh(self.game.state, self.game.table, self.game.sink);
        self.check(refreshed);
    }

    /// Starts one continuous effect from this ability that changes each of `permanents` in a
    /// layer ([CR 611.2c](https://yawgatog.com/resources/magic-rules/#R6112c)): "the set of
    /// objects it affects is determined when that continuous effect begins. After that point,
    /// the set won't change." They are the permanents as they are now; the effect has one
    /// timestamp, whichever of them it changes
    /// ([CR 613.7](https://yawgatog.com/resources/magic-rules/#R6137)).
    pub fn add_effect_on_set(
        &mut self,
        permanents: Bitboard<L::Slot>,
        change: LayerChange,
        duration: Duration,
    ) {
        let source = self.resolution.entry.card;
        let pushed = (self.game.state).start_effect_on_set(source, permanents, change, duration);
        self.check(pushed);
        let refreshed = layers::refresh(self.game.state, self.game.table, self.game.sink);
        self.check(refreshed);
    }

    /// This ability's controller gains control of a permanent
    /// ([CR 613.1b](https://yawgatog.com/resources/magic-rules/#R6131b)): a layer-2 effect.
    /// It has not been under its new controller's control since their most recent turn began
    /// ([CR 302.6](https://yawgatog.com/resources/magic-rules/#R3026)).
    ///
    /// # Panics
    ///
    /// For an emblem's ability, which has no source.
    pub fn gain_control(&mut self, object: ObjectRef<L>, duration: Duration) {
        if !self.game.on_battlefield(object) {
            return;
        }
        let player = self.resolution.entry.controller;
        self.add_effect(
            object,
            Payload::Layer(LayerChange::Control(player)),
            duration,
        );
        self.game.state.set_summoning_sick(object.slot, true);
        let r = event::settle(
            self.game.state,
            self.game.table,
            self.game.sink,
            event::Event::GainControl { object, player },
        );
        self.check(r);
    }
}
