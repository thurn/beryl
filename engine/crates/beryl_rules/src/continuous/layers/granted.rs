//! Static abilities granted to permanents in layer 6 whose effects the layers apply: one
//! whose effect belongs to an earlier layer is found only once that layer has applied, so the
//! layers run once more with it present.
//!
//! Implements: none. Lists the effects of static abilities granted in the layers.

use beryl_kernel::derive::Rederive;

use crate::card::{Ability, GrantIx};
use crate::fixed::Full;
use crate::ids::CardId;
use crate::layout::{Layout, Queue, index};
use crate::state::{AbilityMask, GrantRef, GrantSource};
use crate::table::GameTable;

/// The most times one recompute runs the layers: once, and again for each time a static
/// ability granted in layer 6 is found that the run before did not apply ([`Granted`]).
pub(super) const PASSES: u8 = 3;

/// The static abilities with a continuous effect that a run of the layers found granted to
/// permanents in layer 6, by the battlefield position of the permanent and what grants it.
/// An effect of such an ability may belong to a layer before 6, which had applied by the
/// time the ability was found, so the layers run once more with it present ([CR 613.1]):
/// "all applicable continuous effects are applied in a series of layers in the following
/// order". A game none of whose cards grants such an ability ([`Capability::GrantsLayerEffect`])
/// runs them once.
///
/// [CR 613.1]: https://yawgatog.com/resources/magic-rules/#R6131
pub(super) type Granted<L> = Option<<L as Layout>::Queue<GrantedTo<L>, 8>>;

/// One static ability of a [`Granted`]: the battlefield position of the permanent it is
/// granted to, and what grants it.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub(super) struct GrantedTo<L: Layout> {
    pub(super) at: u16,
    pub(super) grant: GrantRef<L>,
}

/// Filler for the list's unused places.
impl<L: Layout> Default for GrantedTo<L> {
    fn default() -> Self {
        GrantedTo {
            at: 0,
            grant: GrantRef {
                card: L::Card::FIRST,
                grant: GrantIx::new(0),
            },
        }
    }
}

/// The entries of a [`Granted`], none if it has none.
pub(super) fn slice<L: Layout>(
    granted: Option<&<L as Layout>::Queue<GrantedTo<L>, 8>>,
) -> &[GrantedTo<L>] {
    granted.map_or(&[], |g| g.as_slice())
}

/// The static abilities with a continuous effect granted to the permanents now ([`Granted`]),
/// in battlefield order. [`Full`] if they are more than it has places for.
///
/// Out of line: only a game with a card that grants one comes here.
#[inline(never)]
pub(super) fn granted_layer_effects<L: Layout>(
    s: &Rederive<'_, L>,
    t: &GameTable,
) -> Result<Granted<L>, Full> {
    let mut found: Granted<L> = None;
    let rows = s.grant_rows();
    for (i, permanent) in s.rows().iter().enumerate() {
        let granted = permanent.granted;
        for row in
            (rows.iter().enumerate()).filter_map(|(k, row)| granted.has_row(k).then_some(row))
        {
            let Some(grant) = row.as_grant_ref() else {
                continue;
            };
            if granted_ability(t, grant).layer().is_some() {
                // The layout index names every battlefield position.
                let at = index::<L>(i).into();
                found
                    .get_or_insert_with(Default::default)
                    .push(GrantedTo { at, grant })?;
            }
        }
    }
    Ok(found)
}

/// The ability `grant` names: one of its card's front face's [`crate::card::Face::grants`].
#[allow(
    clippy::disallowed_methods,
    reason = "a granted ability is printed on its granting card's front face"
)]
pub(super) fn granted_ability<L: Layout>(t: &GameTable, grant: GrantRef<L>) -> &'static Ability {
    &t.def(grant.card).front().grants[grant.grant.index()]
}

/// The [`Apply::order`] of a static ability granted to a permanent: this bit, with the
/// ability's index among its granting card's grants. It comes after the abilities of the
/// permanent's face, with the permanent's timestamp (see [CR 613.7a]): "A continuous effect
/// generated by a static ability has the same timestamp as the object the static ability is
/// on".
///
/// [CR 613.7a]: https://yawgatog.com/resources/magic-rules/#R6137a
pub(super) const GRANTED: u8 = 0x80;

/// Where the effect a layer change is a part of comes from, as a row of the table of grants
/// records it: the permanent a static ability is on, at the battlefield position `from`, or
/// `source`, the card a resolved spell or ability came from.
pub(super) fn granter<L: Layout>(
    s: &Rederive<'_, L>,
    from: Option<(L::Index, bool)>,
    source: L::Card,
) -> GrantSource<L> {
    match from {
        Some((from, _)) => GrantSource::Permanent(s.battlefield()[Into::<usize>::into(from)]),
        None => GrantSource::Effect(source),
    }
}

/// Whether the permanent at battlefield position `at` has a row of the table of grants, of
/// those written so far in this run of the layers, that grants it the static ability `a` is a
/// part of ([`GRANTED`]).
pub(super) fn granted_so_far<L: Layout>(
    s: &Rederive<'_, L>,
    at: usize,
    a: &super::Apply<L>,
) -> bool {
    let grant = GrantIx::new(a.order & !GRANTED);
    let granted = s.rows()[at].granted;
    (s.grant_rows().iter().enumerate()).any(|(k, row)| {
        granted.has_row(k) && !row.is_lent() && (row.card, row.grant) == (a.source, grant)
    })
}

/// The unresolved layer change for a static ability part whose value is read as the layers
/// apply (`LayerChange::Read` for an amount, `LayerChange::Lend` for `Modification::Lend`).
pub(super) fn unresolved_static_change(
    modification: crate::card::Modification,
    face: crate::card::FaceIx,
    ability: crate::card::AbilityIx,
    part: u8,
) -> crate::state::LayerChange {
    if matches!(modification, crate::card::Modification::Lend(_)) {
        crate::state::LayerChange::Lend {
            face,
            ability,
            part,
        }
    } else {
        crate::state::LayerChange::Read {
            layer: beryl_kernel::effects::read_layer(modification),
            face,
            ability,
            part,
        }
    }
}

/// The zero-based place of `(face, ability, part)` among `source`'s [`crate::card::Modification::Lend`]
/// parts across all its faces, stored in a lent row of the table of grants.
#[allow(
    clippy::disallowed_methods,
    reason = "indexes a lending static ability on its printed card definition"
)]
pub(super) fn lent_index<L: Layout>(
    t: &GameTable,
    source: L::Card,
    face: crate::card::FaceIx,
    ability: crate::card::AbilityIx,
    part: u8,
) -> u8 {
    let mut seen: u8 = 0;
    for (f_ix, f) in t.def(source).faces.iter().enumerate() {
        for (a_ix, a) in f.abilities.iter().enumerate() {
            let Some(spec) = a.layer() else { continue };
            for (p_ix, m) in spec.modifications.iter().enumerate() {
                if matches!(m, crate::card::Modification::Lend(_)) {
                    if f_ix == usize::from(face.get())
                        && a_ix == ability.index()
                        && p_ix == usize::from(part)
                    {
                        return seen;
                    }
                    seen += 1;
                }
            }
        }
    }
    unreachable!("a LayerChange::Lend names a Modification::Lend on its card")
}
