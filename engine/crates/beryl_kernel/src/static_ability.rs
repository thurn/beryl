/// The condition of `ability`'s trigger, if it is a state trigger (see CR 603.8).
pub fn state_condition(ability: &beryl_card::Ability) -> Option<&'static Condition> {
    let TriggerEvent::State(condition) = ability.trigger()?.event else {
        return None;
    };
    Some(condition)
}

/// Whether a change in whether `condition` holds always marks the layer results stale, so
/// that a state trigger with it needs to be matched only after they were stored
/// (`beryl_rules`' `match_states`): a comparison of amounts as a static ability's "as long
/// as" reads them (`counted`), whose inputs the layers watch ([`Inputs::of`]), or a
/// combination of such comparisons. Each variant is placed here, so a new one must be.
pub fn watched(condition: &Condition) -> bool {
    match condition {
        Condition::Compare(left, _, right) => counted(left).is_some() && counted(right).is_some(),
        Condition::Not(condition) => watched(condition),
        Condition::All(conditions) | Condition::Any(conditions) => conditions.iter().all(watched),
        Condition::Paid(_)
        | Condition::Did
        | Condition::WonFlip
        | Condition::Is(..)
        | Condition::EnteredThisTurn(_)
        | Condition::OnBattlefield(_)
        | Condition::Cast(_)
        | Condition::HasChosenName(_)
        | Condition::DrewInDrawStep(_)
        | Condition::TurnOf(_)
        | Condition::AttackedThisTurn(_)
        | Condition::MeldPair(_)
        | Condition::Token(_) => false,
    }
}

/// Whether `filter` asks if a permanent is tapped.
fn mentions_tapped(filter: Filter) -> bool {
    match filter {
        Filter::Tapped => true,
        Filter::Not(filter) => mentions_tapped(*filter),
        Filter::All(filters) | Filter::AnyOf(filters) => {
            filters.iter().any(|&filter| mentions_tapped(filter))
        }
        Filter::Any
        | Filter::Types(_)
        | Filter::Supertypes(_)
        | Filter::SubtypeWord(_)
        | Filter::ColorWords(_)
        | Filter::Whose(_)
        | Filter::Owned(_)
        | Filter::AttackedThisTurn
        | Filter::WithCounter(_)
        | Filter::Token
        | Filter::Named(_)
        | Filter::ManaValueAtMost(_)
        | Filter::PowerAtMost(_)
        | Filter::ManaValueAtMostX
        | Filter::ManaValueAtMostPower
        | Filter::InZone(_) => false,
    }
}

/// Whether `filter` asks if a permanent has a counter of some kind.
fn mentions_counter(filter: Filter) -> bool {
    match filter {
        Filter::WithCounter(_) => true,
        Filter::Not(filter) => mentions_counter(*filter),
        Filter::All(filters) | Filter::AnyOf(filters) => {
            filters.iter().any(|&filter| mentions_counter(filter))
        }
        Filter::Any
        | Filter::Types(_)
        | Filter::Supertypes(_)
        | Filter::SubtypeWord(_)
        | Filter::ColorWords(_)
        | Filter::Whose(_)
        | Filter::Owned(_)
        | Filter::Tapped
        | Filter::AttackedThisTurn
        | Filter::Token
        | Filter::Named(_)
        | Filter::ManaValueAtMost(_)
        | Filter::PowerAtMost(_)
        | Filter::ManaValueAtMostX
        | Filter::ManaValueAtMostPower
        | Filter::InZone(_) => false,
    }
}

/// Whether `condition` asks a filter predicate of the permanent with the ability or of the
/// permanents it counts.
fn condition_reads_filter(condition: &Condition, mentions: fn(Filter) -> bool) -> bool {
    match condition {
        Condition::Is(_, filter) => mentions(*filter),
        Condition::Compare(..) => compares(
            condition,
            &|n| matches!(n, Counted::Permanents(f) if mentions(*f)),
        ),
        Condition::Not(condition) => condition_reads_filter(condition, mentions),
        Condition::All(conditions) | Condition::Any(conditions) => conditions
            .iter()
            .any(|condition| condition_reads_filter(condition, mentions)),
        Condition::Paid(_)
        | Condition::Did
        | Condition::WonFlip
        | Condition::EnteredThisTurn(_)
        | Condition::OnBattlefield(_)
        | Condition::Cast(_)
        | Condition::HasChosenName(_)
        | Condition::DrewInDrawStep(_)
        | Condition::TurnOf(_)
        | Condition::AttackedThisTurn(_)
        | Condition::MeldPair(_)
        | Condition::Token(_) => false,
    }
}

/// Whether `condition` compares an amount, as a static ability's condition reads it
/// ([`counted`]), that `read` accepts.
fn compares(condition: &Condition, read: &dyn Fn(&Counted) -> bool) -> bool {
    let mentions = |amount: &Amount| counted(amount).is_some_and(|n| read(&n));
    match condition {
        Condition::Compare(left, _, right) => mentions(left) || mentions(right),
        Condition::Not(condition) => compares(condition, read),
        Condition::All(conditions) | Condition::Any(conditions) => {
            conditions.iter().any(|condition| compares(condition, read))
        }
        Condition::Did
        | Condition::Paid(_)
        | Condition::Is(..)
        | Condition::EnteredThisTurn(_)
        | Condition::OnBattlefield(_)
        | Condition::Cast(_)
        | Condition::HasChosenName(_)
        | Condition::MeldPair(_)
        | Condition::Token(_)
        | Condition::WonFlip
        | Condition::DrewInDrawStep(_)
        | Condition::TurnOf(_)
        | Condition::AttackedThisTurn(_) => false,
    }
}

/// Whether the layers' reading of `amount` counts cards in graveyards.
fn reads_graveyards(amount: &Amount) -> bool {
    match amount {
        Amount::CardTypesAmong(Objects::All {
            zone: Zone::Graveyard,
            ..
        }) => true,
        Amount::Times(_, amount) | Amount::Plus(_, amount) | Amount::Half { of: amount, .. } => {
            reads_graveyards(amount)
        }
        Amount::Fixed(_)
        | Amount::X
        | Amount::ThatMany
        | Amount::Carried
        | Amount::ThoseOf(_)
        | Amount::Count(_)
        | Amount::CardTypesAmong(_)
        | Amount::Power(_)
        | Amount::Toughness(_)
        | Amount::ManaValue(_)
        | Amount::Counters(..)
        | Amount::Life(_)
        | Amount::Most(..)
        | Amount::SpellsCast(_)
        | Amount::CardsDrawn(_)
        | Amount::SpellsCastBefore => false,
    }
}

impl<L: Layout> State<L> {
    /// Whether a change in the number of `kind` counters on the object in `slot` can change
    /// a layer result, so that the counter mutators mark the results stale
    /// ([`State::add_counters`]). Only +1/+1 and -1/-1 counters modify power and toughness
    /// (see [CR 613.4c]): "Effects and counters that modify power and/or toughness ... are
    /// applied". Any other kind matters only when a static ability on the battlefield filters
    /// by counters ([`Inputs::ANY_COUNTERS`]), or to a static ability of its own permanent
    /// whose "as long as" compares it while some permanent's ability compares counters
    /// ([`Inputs::COUNTERS`]): loyalty, which planeswalkers gain and lose every turn, never
    /// does otherwise.
    ///
    /// A state trigger's condition that compares the kind counts as such an "as long as"
    /// ([`watched`]).
    ///
    /// [CR 613.4c]: https://yawgatog.com/resources/magic-rules/#R6134c
    #[inline]
    pub fn layers_read_counters(&self, t: &GameTable, slot: L::Slot, kind: CounterKind) -> bool {
        matches!(kind, CounterKind::PlusOne | CounterKind::MinusOne)
            || !self.object(slot).on_battlefield()
            || self.layer_inputs.contains(Inputs::ANY_COUNTERS)
            || (self.layer_inputs.contains(Inputs::COUNTERS)
                && self.definition(slot).face(t).abilities.iter().any(|a| {
                    a.layer()
                        .and_then(|spec| spec.condition.as_ref())
                        .or_else(|| state_condition(a))
                        .is_some_and(|condition| reads_counters(condition, kind))
                }))
    }

    /// Whether a card moving into or out of a graveyard can change a layer result: whether
    /// a permanent on the battlefield counts the cards in graveyards
    /// ([`Inputs::GRAVEYARDS`]).
    #[inline]
    pub(crate) fn layers_read_graveyards(&self) -> bool {
        self.layer_inputs.contains(Inputs::GRAVEYARDS)
    }

    /// Whether a card moving into or out of a hand can change a layer result.
    pub(crate) fn layers_read_hands(&self) -> bool {
        self.layer_inputs.contains(Inputs::HAND)
    }

    /// Whether a card joining or leaving the cards exiled with a permanent can change a layer
    /// result ([`Inputs::LINKED`]).
    #[inline]
    pub(crate) fn layers_read_linked(&self) -> bool {
        self.layer_inputs.contains(Inputs::LINKED)
    }
}

/// Why the layers cannot apply a static ability: the part of it no code reads.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Unapplied {
    /// It says something only a resolving spell or ability has
    /// ([`LayerSpec::needs_a_resolution`]): a target, X, "that player", or what an
    /// instruction before did. No code could read it: a static ability never resolves.
    Resolving,
    /// It affects a set the layers do not find: any but the permanent it is on, the one that
    /// permanent is attached to, and the permanents a filter of what the layers read
    /// accepts ([`read_by_the_layers`]). Objects in other zones have no layer results.
    Affected,
    /// Its "as long as" reads something the layers do not have as they apply: anything but
    /// a cost paid for the permanent it is on, the counters on that permanent, whether that
    /// permanent passes a filter, and the number of permanents that pass one, each filter
    /// one of what the layers read ([`read_by_the_layers`]).
    Condition,
    /// "Power is equal to [amount]" said by anything but a characteristic-defining ability:
    /// by a static ability of another permanent or one with a condition, or by a resolving
    /// spell or ability. Either sets a power alone in layer 7b, which the engine has only
    /// as a base power and toughness together ([`Modification::SetBasePt`]).
    SetPower,
    /// A power or base power and toughness is an amount the layers do not read as they
    /// apply: anything but a number, a count of permanents by their characteristics and
    /// controllers, the number of card types among cards in all graveyards, and a multiple
    /// of one or one plus a number.
    Amount,
    /// A static ability a card grants reads an amount as its layer applies: the layers read
    /// amounts by the ability's place on its permanent's face, and a granted one has none.
    GrantedAmount,
}

/// Whether the layers apply a static ability's continuous effect, or why they cannot.
pub fn applied(spec: &LayerSpec) -> Result<(), Unapplied> {
    if spec.needs_a_resolution() {
        return Err(Unapplied::Resolving);
    }
    if !found_by_the_layers(spec.affected) {
        return Err(Unapplied::Affected);
    }
    match &spec.condition {
        Some(condition) if !reads(condition) => return Err(Unapplied::Condition),
        _ => {}
    }
    read_amounts(spec)
}

/// Whether the layers find the permanents a static ability affects
/// ([`Unapplied::Affected`]): the permanent it is on, the one that permanent is attached to,
/// the permanents a filter of what the layers read accepts, and those but the permanent with
/// the ability ([`Objects::Other`]).
fn found_by_the_layers(affected: Objects) -> bool {
    match affected {
        Objects::This | Objects::AttachedTo => true,
        // Everywhere: every permanent the filter accepts. The objects off the battlefield
        // it reaches are the kernel's to read (`crate::query::zone_characteristics`).
        Objects::All {
            zone: Zone::Battlefield,
            filter,
        }
        | Objects::Everywhere(filter) => read_by_the_layers(filter),
        Objects::Other(&objects) => {
            matches!(objects, Objects::All { .. }) && found_by_the_layers(objects)
        }
        Objects::Target(_)
        | Objects::Those
        | Objects::TriggeredOn
        | Objects::TriggeredOnIn(_)
        | Objects::Carried
        | Objects::ExiledWithThis
        | Objects::LibraryTop { .. }
        | Objects::ExceptThose(_)
        | Objects::PutOntoBattlefieldWithThis
        | Objects::InZoneOf { .. }
        | Objects::CardsIn { .. }
        | Objects::All { .. }
        | Objects::Paid(_) => false,
    }
}

/// Whether the layers can read each part of a static ability whose amount they read as it
/// applies, or why not. "Power is equal to [amount]" ([`Modification::SetPower`]) has one
/// path, a characteristic-defining ability's
/// (see [CR 604.3a](https://yawgatog.com/resources/magic-rules/#R6043a)): the ability "defines
/// an object's colors, subtypes, power, or toughness", "does not directly affect the
/// characteristics of any other objects" and "does not set the values of such
/// characteristics only if certain conditions are met". Its amount is read as layer 7a
/// applies, against what layers 2 to 6 made of every permanent. "Has base power and
/// toughness [amount]" ([`Modification::SetBasePt`]) applies in layer 7b on any set, and its
/// amounts are read for each permanent as that layer applies. There, and only there, "its
/// mana value" ([`Amount::ManaValue`] of [`Objects::Those`]) is the mana value of each
/// permanent the ability affects: Opalescence's "has base power and base toughness each
/// equal to its mana value" ([`reads_each`]).
pub fn read_amounts(spec: &LayerSpec) -> Result<(), Unapplied> {
    for modification in spec.modifications {
        let Some((power, toughness)) = modification.pt_amounts() else {
            continue;
        };
        let base = matches!(modification, Modification::SetBasePt(..));
        if !base {
            defines(spec)?;
        }
        for amount in [Some(power), toughness].into_iter().flatten() {
            if !(base && is_its_mana_value(amount)) {
                read_as_the_layer_applies(amount)?;
            }
        }
    }
    Ok(())
}

/// Refuses a "power is equal to" said by anything but a characteristic-defining ability: one
/// of the permanent itself with no condition (see [CR 604.3a]).
///
/// [CR 604.3a]: https://yawgatog.com/resources/magic-rules/#R6043a
fn defines(spec: &LayerSpec) -> Result<(), Unapplied> {
    if matches!(spec.affected, Objects::This) && spec.condition.is_none() {
        Ok(())
    } else {
        Err(Unapplied::SetPower)
    }
}

/// The amounts the part at `part` of a static ability's continuous effect reads as its
/// layer applies: the power of a [`Modification::SetPower`], or the power and toughness of
/// a [`Modification::SetPt`] or a [`Modification::SetBasePt`].
///
/// # Panics
///
/// For a part that reads no amount, which the layers list as a settled change instead.
pub fn amounts_of(spec: &LayerSpec, part: u8) -> (&'static Amount, Option<&'static Amount>) {
    spec.modifications[usize::from(part)]
        .pt_amounts()
        .expect("the layers read the amounts of a part that has some")
}

/// Whether the amounts of the part at `part` of a static ability read each permanent it
/// affects ([`read_amounts`]), so that the part changes each permanent its own way and is
/// read once for each.
pub fn reads_each(spec: &LayerSpec, part: u8) -> bool {
    let Modification::SetBasePt(power, toughness) = spec.modifications[usize::from(part)] else {
        return false;
    };
    is_its_mana_value(power) || is_its_mana_value(toughness)
}

/// "Its mana value", said of each permanent a static ability affects ([`read_amounts`]).
fn is_its_mana_value(amount: &Amount) -> bool {
    matches!(amount, Amount::ManaValue(Objects::Those))
}

/// Refuses an amount the layers cannot read as they apply: they have each permanent's
/// characteristics and controller as the layers before left them, and the card types of the
/// cards in graveyards, which no layer changes.
fn read_as_the_layer_applies(amount: &Amount) -> Result<(), Unapplied> {
    match *amount {
        Amount::Times(_, amount) | Amount::Plus(_, amount) | Amount::Half { of: amount, .. } => {
            read_as_the_layer_applies(amount)
        }
        Amount::Count(&Objects::All {
            zone: Zone::Battlefield,
            filter,
        }) if read_by_the_layers(filter) => Ok(()),
        // Cards in graveyards have no layer results: their card types are their cards'.
        // A move into or out of a graveyard marks the results stale while a permanent
        // reads them ([`Inputs::GRAVEYARDS`]).
        Amount::Fixed(_)
        | Amount::CardTypesAmong(&Objects::All {
            zone: Zone::Graveyard,
            filter: Filter::Any,
        }) => Ok(()),
        Amount::X
        | Amount::ThatMany
        | Amount::Carried
        | Amount::ThoseOf(_)
        | Amount::Count(_)
        | Amount::CardTypesAmong(_)
        | Amount::Power(_)
        | Amount::Toughness(_)
        | Amount::ManaValue(_)
        | Amount::Counters(..)
        | Amount::Life(_)
        | Amount::Most(..)
        | Amount::SpellsCast(_)
        | Amount::CardsDrawn(_)
        | Amount::SpellsCastBefore => Err(Unapplied::Amount),
    }
}

/// Whether the layers can read `filter` of a permanent as they apply: it asks for the
/// permanent's characteristics and who controls it, which the layers before have settled,
/// or for whether it is tapped and its mana value, which no layer changes. "Mana value X or
/// less" names a resolution's X, which a static ability has none of.
pub fn read_by_the_layers(filter: Filter) -> bool {
    match filter {
        Filter::Any
        | Filter::Types(_)
        | Filter::Supertypes(_)
        | Filter::SubtypeWord(_)
        | Filter::ColorWords(_)
        | Filter::Whose(_)
        | Filter::Owned(_)
        | Filter::Tapped
        | Filter::WithCounter(_)
        | Filter::Token
        | Filter::Named(_)
        | Filter::ManaValueAtMost(_)
        | Filter::InZone(_) => true,
        // The layers have no resolution X or attack history input. Reading power in earlier
        // layers requires dependency ordering because layer 7 writes power.
        Filter::ManaValueAtMostX
        | Filter::ManaValueAtMostPower
        | Filter::PowerAtMost(_)
        | Filter::AttackedThisTurn => false,
        Filter::Not(filter) => read_by_the_layers(*filter),
        Filter::All(filters) | Filter::AnyOf(filters) => {
            filters.iter().all(|&filter| read_by_the_layers(filter))
        }
    }
}

/// Whether an instruction, or one inside it, sets a power to an amount.
fn sets_power(effect: &Effect) -> bool {
    effect.any(&|effect| {
        effect
            .modifications()
            .iter()
            .any(|m| matches!(m, Modification::SetPower(_) | Modification::SetPt(..)))
    })
}

/// The first static ability of a card's faces, or of the abilities they grant, that the
/// layers cannot apply.
pub(crate) fn check(def: &CardDef) -> Result<(), Unapplied> {
    let abilities = || (def.faces.iter()).flat_map(|face| face.abilities.iter().chain(face.grants));
    // A resolving ability's effect cannot set a power to an amount either: it would lock
    // the number in as it begins, in a layer the engine does not have.
    if abilities()
        .any(|ability| matches!(ability.body(), Behavior::Data(effect) if sets_power(effect)))
    {
        return Err(Unapplied::SetPower);
    }
    abilities()
        .filter_map(beryl_card::Ability::layer)
        .try_for_each(applied)?;
    let granted = || (def.faces.iter()).flat_map(|face| face.grants.iter());
    if granted()
        .filter_map(beryl_card::Ability::layer)
        .any(|spec| spec.modifications.iter().any(|&m| read_layer_amount(m)))
    {
        return Err(Unapplied::GrantedAmount);
    }
    Ok(())
}

/// Whether the layers read the amount of `modification` as its layer applies, rather than
/// settling it as the ability is listed. A characteristic-defining amount is always read
/// as the layer applies. Base power and toughness can be settled when both are numbers.
fn read_layer_amount(modification: Modification) -> bool {
    let Some((power, toughness)) = modification.pt_amounts() else {
        return false;
    };
    !matches!(modification, Modification::SetBasePt(..))
        || !matches!(
            (power, toughness),
            (Amount::Fixed(_), Some(Amount::Fixed(_)))
        )
}

/// Whether [`holds`] reads `condition`.
fn reads(condition: &Condition) -> bool {
    match condition {
        Condition::Paid(_) => true,
        Condition::Compare(left, _, right) => counted(left).is_some() && counted(right).is_some(),
        Condition::Is(Objects::This, filter) => read_by_the_layers(*filter),
        Condition::Not(condition) => reads(condition),
        Condition::All(conditions) | Condition::Any(conditions) => conditions.iter().all(reads),
        Condition::Did
        | Condition::WonFlip
        | Condition::Is(..)
        | Condition::EnteredThisTurn(_)
        | Condition::OnBattlefield(_)
        | Condition::Cast(_)
        | Condition::HasChosenName(_)
        | Condition::DrewInDrawStep(_)
        | Condition::TurnOf(_)
        | Condition::AttackedThisTurn(_)
        | Condition::MeldPair(_)
        | Condition::Token(_) => false,
    }
}

/// Whether `condition` reads the layers' own results: whether the permanent with the ability
/// passes a filter, or how many permanents do. Such a condition is read as its effect's
/// layer applies, against what the layers before it made of every permanent; any other is
/// the same before and after the layers run.
pub fn reads_results(condition: &Condition) -> bool {
    match condition {
        Condition::Is(..) => true,
        Condition::Compare(left, _, right) => [left, right].into_iter().any(|amount| {
            matches!(
                counted(amount),
                Some(Counted::Permanents(_) | Counted::Hand)
            )
        }),
        Condition::Not(condition) => reads_results(condition),
        Condition::All(conditions) | Condition::Any(conditions) => {
            conditions.iter().any(reads_results)
        }
        Condition::Paid(_)
        | Condition::Did
        | Condition::WonFlip
        | Condition::EnteredThisTurn(_)
        | Condition::OnBattlefield(_)
        | Condition::Cast(_)
        | Condition::HasChosenName(_)
        | Condition::DrewInDrawStep(_)
        | Condition::TurnOf(_)
        | Condition::AttackedThisTurn(_)
        | Condition::MeldPair(_)
        | Condition::Token(_) => false,
    }
}

/// An amount a static ability's condition may compare.
enum Counted {
    /// A number printed on the card.
    Number(u8),
    /// The counters of a kind on the permanent with the ability.
    Counters(CounterKind),
    /// The number of permanents the filter accepts, read for the controller of the
    /// permanent with the ability.
    Permanents(Filter),
    /// The life total of the controller of the permanent with the ability ("you"), or the
    /// total of their opponents' ("each opponent", which in a two-player game is the one
    /// opponent's).
    Life(Players),
    Hand,
}

/// `amount` as a static ability's condition may compare it, or `None` for any other amount.
fn counted(amount: &Amount) -> Option<Counted> {
    match amount {
        Amount::Fixed(n) => Some(Counted::Number(*n)),
        Amount::Counters(Objects::This, kind) => Some(Counted::Counters(*kind)),
        Amount::Count(Objects::All {
            zone: Zone::Battlefield,
            filter,
        }) if read_by_the_layers(*filter) => Some(Counted::Permanents(*filter)),
        Amount::Count(Objects::InZoneOf {
            zone: Zone::Hand,
            players: Players::You,
            filter: Filter::Any,
        }) => Some(Counted::Hand),
        Amount::Life(players @ (Players::You | Players::EachOpponent)) => {
            Some(Counted::Life(*players))
        }
        Amount::X
        | Amount::ThatMany
        | Amount::Carried
        | Amount::ThoseOf(_)
        | Amount::Count(_)
        | Amount::Times(..)
        | Amount::Half { .. }
        | Amount::Plus(..)
        | Amount::CardTypesAmong(_)
        | Amount::Power(_)
        | Amount::Toughness(_)
        | Amount::ManaValue(_)
        | Amount::Counters(..)
        | Amount::Life(_)
        | Amount::Most(..)
        | Amount::SpellsCast(_)
        | Amount::CardsDrawn(_)
        | Amount::SpellsCastBefore => None,
    }
}

/// What the layers have made of the permanents so far, for a condition that reads it
/// ([`reads_results`]): the rules implement it over the results of the layers before the
/// one the condition's effect applies in.
pub trait LayerResults {
    /// Whether the permanent with the ability passes `filter`.
    fn is(&self, filter: Filter) -> bool;
    /// The number of permanents that pass `filter`, read for the controller of the
    /// permanent with the ability.
    fn count(&self, filter: Filter) -> usize;
    fn own_hand(&self) -> u32;
}

/// No layer results, for a condition that reads none: what a caller passes [`holds`] for a
/// condition [`reads_results`] says no to.
pub struct NoResults;

impl LayerResults for NoResults {
    fn is(&self, _: Filter) -> bool {
        unreachable!("a condition that reads the layer results is read as they apply")
    }

    fn own_hand(&self) -> u32 {
        unreachable!("the controller is known when the layer applies")
    }

    fn count(&self, _: Filter) -> usize {
        unreachable!("a condition that reads the layer results is read as they apply")
    }
}

/// Whether a static ability's "as long as" holds for the permanent in `slot`, which has the
/// ability. What the layers start from is read from the state; whether a permanent passes a
/// filter, and how many do, from `results`, what the layers have made of them so far.
///
/// # Panics
///
/// For a condition [`applied`] refuses, which no static ability of a game's table has.
pub fn holds<L: Layout>(
    s: &State<L>,
    slot: L::Slot,
    condition: &Condition,
    results: &impl LayerResults,
) -> bool {
    let amount = |amount: &Amount| match counted(amount) {
        Some(Counted::Number(n)) => i32::from(n),
        Some(Counted::Counters(kind)) => i32::from(s.counters_of(slot, kind)),
        Some(Counted::Hand) => i32::try_from(results.own_hand()).unwrap_or(i32::MAX),
        Some(Counted::Permanents(filter)) => {
            i32::try_from(results.count(filter)).unwrap_or(i32::MAX)
        }
        // See CR 119.1: a player's life total, read from the state as the layers apply.
        Some(Counted::Life(players)) => {
            // The layers have not run yet, so this is the controller before layer 2: a
            // permanent whose control another effect changes reads its "you" as its owner's
            // side until then.
            let controller = s.base_controller(slot);
            let who = match players {
                Players::You => PlayerSet::only(controller),
                Players::EachOpponent
                | Players::EachPlayer
                | Players::Target(_)
                | Players::ControllerOf(_)
                | Players::OwnerOf(_)
                | Players::Enchanted
                | Players::ThatPlayer
                | Players::SubgameNonwinners
                | Players::EachOther(_) => s.opponents_of(controller),
            };
            who.in_seat_order()
                .map(|p| i32::from(s.player(p).life()))
                .sum()
        }
        None => unreachable!("the card table refuses a static ability that compares this"),
    };
    match condition {
        // See CR 702.33d: a permanent remembers each kind of cost its spell paid.
        Condition::Paid(kind) => s.paid(slot, *kind),
        Condition::Compare(left, comparison, right) => {
            comparison.holds(amount(left), amount(right))
        }
        Condition::Is(Objects::This, filter) => results.is(*filter),
        Condition::Not(condition) => !holds(s, slot, condition, results),
        Condition::All(conditions) => conditions.iter().all(|c| holds(s, slot, c, results)),
        Condition::Any(conditions) => conditions.iter().any(|c| holds(s, slot, c, results)),
        Condition::Did
        | Condition::WonFlip
        | Condition::Is(..)
        | Condition::EnteredThisTurn(_)
        | Condition::OnBattlefield(_)
        | Condition::Cast(_)
        | Condition::HasChosenName(_)
        | Condition::DrewInDrawStep(_)
        | Condition::TurnOf(_)
        | Condition::AttackedThisTurn(_)
        | Condition::MeldPair(_)
        | Condition::Token(_) => {
            unreachable!("the card table refuses a static ability with this condition")
        }
    }
}

